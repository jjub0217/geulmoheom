#!/usr/bin/env node
/**
 * 화면 문구가 `docs/문구.md` 를 벗어났는지 본다 (`주차계획/W6.md` **13번**).
 *
 * ⛔ 왜 있나 — **나흘에 넷이고 둘이 운영까지 갔다.** 하나는 **대표 승인된 프라이버시 고지**,
 * 하나는 **일주일째** 화면에 떠 있었다. **넷 다 사람이 우연히 찾았다** — 다음에도
 * 찾힌다는 보장이 없다.
 *
 * ## 방향은 「코드 → 문서」 한쪽이다
 *
 * 코드의 화면 문자열이 **`문구.md` 안에 그대로 있는가**만 본다. **넷 다 이 방향으로 잡힌다** —
 * 버린 문장이 코드에 남으면 문서에서 사라졌으니 빨간불이다.
 *
 * **⛔ 반대 방향은 안 잡는다.** 「문서에 자리가 생겼는데 코드가 없다」는 **거짓말이 아니라
 * 미구현**이라 급이 다르고, 잡으려면 표를 파싱해야 해서 **문서 서식이 바뀔 때마다 검사가 깨진다.**
 *
 * **⛔ 그래서 이 검사는 문서를 고치라고 말하지 않는다.** 나오는 말은 언제나
 * **「코드를 고쳐라」**다 — 문서가 먼저 바뀌는 것이 정상 순서이고, 장치가 그 순서를
 * 거꾸로 세우면 **문구를 고칠 때마다 PM 이 막히고 결국 아무도 문서를 안 고친다.**
 *
 * ## 자리가 루트인 이유
 *
 * **넷째가 `api/app/errors.py` 였다.** `web` 만 보는 장치는 **넷 중 하나를 못 잡는다** —
 * 아이 화면 문구가 **두 패키지에서 나간다.**
 *
 * ## 한계 둘 — 정직하게 적는다
 *
 * ① **값이 끼는 문장**(`${별명}을 지울까요?`)은 그대로 비교가 안 된다. **세지 않고 「못 잰 것」**
 *    으로 따로 찍는다 — 조용히 통과시키면 **검사가 덮은 자리를 아무도 모른다.**
 * ⓐ **버린 문장이 표 칸 안에 취소선 없이 인용되면 못 잡는다.** 아래 「무엇과 대조하나」 참조.
 * ⓑ **문서가 스스로 낡으면 그만큼 못 잡는다.** 2026-09-15 실측 — **프라이버시 고지(3.1)의
 *    옛 문장을 되돌려 봤는데 통과했다.** `문구.md` **0장 「목소리」 표가 그 옛 문장을 예시로
 *    들고 있어서**다. **예시가 실린 표와 문구가 사는 표를 이 검사는 구분하지 못한다** —
 *    구분하려면 표마다 머리글을 해석해야 하고, 그러면 **문서 서식이 바뀔 때마다 검사가 깨진다.**
 *    **PM 에게 그 예시를 알렸다** — 문서가 한 벌로 맞으면 이 자리도 자동으로 잡힌다.
 * ② **예외는 이유를 강제한다.** 중앙 목록을 두면 **쓰레기통이 되므로**, 예외는 **그 줄 옆에**
 *    `문구없음: <이유>` 로 적는다. **이유가 짧으면 검사가 그것을 실패로 센다.**
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";

const 루트 = new URL("..", import.meta.url).pathname;

/** 예외를 여는 표식. **이유를 같이 적지 않으면 안 열린다.** */
const 예외표식 = "문구없음:";
const 이유최소길이 = 10;

/**
 * 볼 파일. **훑어서 모으지 않고 적어 둔다** — 글로브로 모으면 **새 파일이 조용히 검사 밖에
 * 생기는데**, 그때 검사는 **초록인 채로 아무것도 안 본다.** 적어 두면 늘릴 때 사람이 안다.
 */
const 볼파일 = [
  "web/src/app/copy.ts",
  "web/src/app/app-copy.ts",
  "web/src/app/status-copy.ts",
  "web/src/app/book/copy.ts",
  "web/src/app/child/auth/copy.ts",
  "web/src/app/parents/login/copy.ts",
  "web/src/app/parents/signup/copy.ts",
  "web/src/components/artwork-copy.ts",
  "web/src/components/children-copy.ts",
  "web/src/components/leave-copy.ts",
  // **넷째가 여기였다.** 아이 화면 문구가 두 패키지에서 나간다.
  // **블록을 못 박는다** — 이 파일에는 **로그·예외 문구**도 있고 그건 화면에 안 나간다.
  // 그리고 **`api/` 는 백엔드 모자의 파일**이라, 예외 표식을 달러 들어가지 않는 것이
  // **이 검사가 남의 패키지에 손대지 않는 방법**이다.
  { 경로: "api/app/errors.py", 블록: "CHILD_MESSAGE" },
];

/**
 * 블록이 지정된 파일은 **그 심볼부터 닫는 중괄호까지만** 본다.
 *
 * **못 찾으면 죽는다.** 심볼 이름이 바뀌면 **검사가 초록인 채로 그 파일을 통째로 안 보게 되고**,
 * 그것이 **가장 위험한 실패 모양**이다.
 */
function 볼줄들(파일, 원문) {
  const 줄들 = 원문.split("\n");
  if (파일.블록 === undefined) return 줄들.map((줄, i) => [줄, i]);
  const 시작 = 줄들.findIndex((줄) => 줄.includes(파일.블록));
  if (시작 === -1) 설정이틀렸다(`${파일.경로} 에서 ${파일.블록} 을 못 찾았다`);
  const 끝 = 줄들.findIndex((줄, i) => i > 시작 && /^\}/.test(줄));
  return 줄들.slice(시작, 끝 === -1 ? undefined : 끝).map((줄, i) => [줄, 시작 + i]);
}

/**
 * ## 무엇과 대조하나 — **문서 전체가 아니다**
 *
 * **`문구.md` 는 버린 문장을 산문에 그대로 인용한다** — 「종전 「조금만 천천히 가볼까요」다」처럼.
 * **그것이 문서의 값**이고(왜 버렸는지가 남는다) **바꾸라고 할 것이 아니다.**
 *
 * **그래서 대조 대상은 「문구가 사는 자리」뿐이다** — **표 칸(`|`)과 인용문(`>`)**.
 * 확정된 문장은 거기 살고, **근거와 기록은 산문에 산다.**
 *
 * **⛔ 안 좁히면 검사가 정확히 제일 중요한 자리를 놓친다.** 2026-09-15 실측 —
 * 전체 대조로는 **`errors.py` 의 `RATE_LIMITED`**(일주일째 떠 있던 옛 문장)가 **통과했다.**
 * 문서가 그 문장을 「종전 …다」로 인용해 뒀기 때문이다.
 *
 * **취소선(`~~…~~`)은 통째로 버린다** — 표 안에 남겨 둔 **폐기 표시**이고,
 * 마커만 벗기면 **버린 문장이 살아 있는 문장으로 읽힌다.**
 *
 * **⚠ 한계 ⓐ — 표 칸 안에 취소선 없이 인용된 옛 문장은 못 잡는다.** 지금은 그런 자리가 없다.
 */
function 문구가사는자리(문서전체) {
  return 문서전체
    .split("\n")
    .map((줄) => 줄.trim())
    .filter((줄) => 줄.startsWith("|") || 줄.startsWith(">"))
    .join("\n")
    .replace(/~~[^~]*~~/g, " ");
}

/**
 * 문서와 코드를 **같은 모양으로** 만든다.
 *
 * 문서는 표 칸 안에서 **굵게(`**`)·취소선(`~~`)·홑따옴표 강조**를 쓰고, 코드는 안 쓴다.
 * 그대로 비교하면 **전부 빨간불**이라 검사가 못 쓰게 된다.
 */
function 고르기(글) {
  return 글
    .replace(/[*~`]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** 한글이 든 문자열만 본다 — 키·클래스 이름·주소는 화면 문구가 아니다. */
const 한글있나 = (글) => /[가-힣]/.test(글);

/**
 * 한 줄에서 문자열 리터럴을 꺼낸다. **따옴표 셋을 다 본다.**
 *
 * **백틱은 값이 끼는지까지 본다** — `${…}` 가 있으면 **그대로 비교가 안 되는 것**이라
 * 못 잰 것으로 넘긴다.
 */
function 문자열들(줄) {
  const 나온것 = [];
  const 정규식 = /"([^"\\]*(?:\\.[^"\\]*)*)"|'([^'\\]*(?:\\.[^'\\]*)*)'|`([^`\\]*(?:\\.[^`\\]*)*)`/g;
  let m;
  while ((m = 정규식.exec(줄)) !== null) {
    const 값 = m[1] ?? m[2] ?? m[3];
    if (값 === undefined || !한글있나(값)) continue;
    나온것.push({ 값, 값이끼나: m[3] !== undefined && /\$\{/.test(m[3]) });
  }
  return 나온것;
}

const 문서 = 고르기(문구가사는자리(readFileSync(join(루트, "docs/문구.md"), "utf8")));

/** 설정이 틀려서 죽는 것과 문구가 어긋나서 죽는 것을 **출력에서 갈라 준다.** */
function 설정이틀렸다(뜻) {
  process.stdout.write(`✘ 검사 설정이 틀렸다 — ${뜻}\n`);
  process.stdout.write("   경로나 블록 이름이 바뀌었다. 고칠 것은 infra/check-copy.mjs 다.\n");
  process.exit(1);
}

const 어긋남 = [];
const 못잰것 = [];
const 예외 = [];
const 이유없는예외 = [];

/** 파일마다 몇 개를 봤는지. **0 이면 검사가 그 파일에 대해 아무 말도 안 한 것**이다. */
const 센것 = new Map();

for (const 것 of 볼파일) {
  const 파일 = typeof 것 === "string" ? { 경로: 것 } : 것;
  const 원문 = readFileSync(join(루트, 파일.경로), "utf8");
  const 전체줄 = 원문.split("\n");
  센것.set(파일.경로, 0);
  볼줄들(파일, 원문).forEach(([줄, i]) => {
    // **주석은 통째로 걷어낸다.** 근거와 기록이 거기 있고 **거기엔 버린 문장도 인용된다** —
    // 그리고 주석은 `문구.md` 처럼 **백틱으로 감싼 말**을 쓰는데, 안 걷어내면
    // 그것이 **템플릿 문자열로 읽혀** 있지도 않은 어긋남이 무더기로 뜬다 (2026-09-15 실측).
    const 벗긴줄 = 줄.trimStart();
    if (/^(\/\/|\/\*|\*|#)/.test(벗긴줄)) return;
    // 줄 끝에 붙은 주석도 자른다. **따옴표 안의 `//` 는 건드리지 않는다** — 화면 문구에
    // 주소가 들어가는 자리가 없어서 이 단순한 잘라내기로 충분하다.
    const 코드부분 = 줄.split(/\s\/\/|\s#/)[0];

    for (const { 값, 값이끼나 } of 문자열들(코드부분)) {
      const 자리 = `${파일.경로}:${i + 1}`;
      센것.set(파일.경로, 센것.get(파일.경로) + 1);
      // **예외는 그 줄 옆에 이유와 함께** 적는다. 앞줄도 본다 — 문장이 길어 줄이 접히는 자리가 있다.
      const 표식줄 = [줄, 전체줄[i - 1] ?? ""].find((t) => t.includes(예외표식));
      if (표식줄 !== undefined) {
        const 이유 = 표식줄.slice(표식줄.indexOf(예외표식) + 예외표식.length).trim();
        if (이유.length < 이유최소길이) 이유없는예외.push({ 자리, 값, 이유 });
        else 예외.push({ 자리, 값, 이유 });
        continue;
      }
      if (값이끼나) {
        못잰것.push({ 자리, 값 });
        continue;
      }
      if (!문서.includes(고르기(값))) 어긋남.push({ 자리, 값 });
    }
  });
}

const 쓰기 = (줄) => process.stdout.write(`${줄}\n`);

쓰기(`문구.md 의 표·인용문과 대조 — 파일 ${볼파일.length}개`);
쓰기("");

if (어긋남.length > 0) {
  쓰기(`✘ 문서에 없는 문장 ${어긋남.length}개 — 코드가 옛말을 하고 있다`);
  for (const { 자리, 값 } of 어긋남) 쓰기(`   ${자리}\n     「${값}」`);
  쓰기("");
}
if (이유없는예외.length > 0) {
  쓰기(`✘ 이유 없는 예외 ${이유없는예외.length}개 — 「${예외표식} <왜 문서에 없는지>」를 적는다`);
  for (const { 자리, 값 } of 이유없는예외) 쓰기(`   ${자리}\n     「${값}」`);
  쓰기("");
}
if (못잰것.length > 0) {
  // **덮은 자리를 보이게 둔다.** 조용히 통과시키면 **검사가 무엇을 안 보는지 아무도 모른다.**
  쓰기(`⚠ 못 잰 것 ${못잰것.length}개 — 값이 껴서 그대로 비교가 안 된다 (한계 ①)`);
  for (const { 자리, 값 } of 못잰것) 쓰기(`   ${자리}  「${값}」`);
  쓰기("");
}
if (예외.length > 0) {
  쓰기(`· 이유를 달고 지나간 예외 ${예외.length}개`);
  for (const { 자리, 이유 } of 예외) 쓰기(`   ${자리}  ${이유}`);
  쓰기("");
}

/**
 * **아무것도 안 본 파일은 실패다.**
 *
 * 경로가 바뀌거나 블록 이름이 바뀌면 **검사는 초록인 채로 그 파일을 통째로 안 본다** —
 * `contracts-check` 가 서버 없이 조용히 통과하던 것과 **같은 부류**이고,
 * **가장 위험한 실패 모양은 빨간불이 아니라 「아무 말도 안 하는 초록」**이다.
 */
const 안본파일 = [...센것].filter(([, 수]) => 수 === 0).map(([경로]) => 경로);
if (안본파일.length > 0) {
  쓰기(`✘ 문자열을 하나도 못 본 파일 ${안본파일.length}개 — 경로나 블록 이름이 바뀌었다`);
  for (const 경로 of 안본파일) 쓰기(`   ${경로}`);
  쓰기("");
}

if (어긋남.length > 0 || 이유없는예외.length > 0 || 안본파일.length > 0) {
  쓰기("→ 고치는 것은 코드다. **`문구.md` 가 SSOT 이고 코드가 따라온다.**");
  쓰기("   문서가 맞는데 코드가 안 따라온 것이면 코드를 문서에 맞춘다.");
  쓰기("   문서에 없어도 되는 문장이면 그 줄 옆에 「문구없음: <이유>」 를 적는다.");
  process.exit(1);
}
쓰기("코드가 문서 안에 있다.");
