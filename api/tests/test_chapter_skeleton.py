"""챕터 뼈대를 **문서에서 읽는다** (`docs/챕터뼈대_초안.md` · W7 1번).

**이 뼈대는 아직 대표 미검수다.** 검수로 바뀔 것이 거의 확실하고, 그때 **코드가
따라와야 한다** — 그래서 문서를 읽는다. 여기서 지키는 것은 **「문서가 바뀌면 알게
되는 것」**이지 특정 문장이 아니다.

**⛔ 본문 문장을 박지 않는다.** 「태엽새」·「발이 톱니에 끼어 있다」를 검사에 넣으면
**검수가 그 문장을 고치는 날 결함이 아닌 빨간불**이 뜬다. 대신 **구조**를 박는다 —
비트 여섯 · 경로 넷 · 시련 9턴 · 조건 공개는 `approach` 부터.
"""

import pytest

from app import chapter_skeleton as 뼈대


def test_비트가_여섯이고_순서가_PRD_와_맞는다():
    """**도입 → 위기 → 시련 → 완결** (PRD A-4). 「위기」가 셋으로 펴져 있다."""
    순서 = [것.beat for 것 in 뼈대.비트시트()]

    assert 순서 == ["intro", "explore", "rising_action", "approach", "trial", "resolution"]


def test_턴범위가_안_겹치고_안_빈다():
    """겹치면 한 턴에 비트가 둘이고, 비면 그 턴에 비트가 없다."""
    덮인턴 = []
    for 것 in 뼈대.비트시트():
        처음, 끝 = 것.턴범위
        assert 처음 <= 끝
        덮인턴.extend(range(처음, 끝 + 1))

    assert 덮인턴 == sorted(덮인턴)
    assert len(덮인턴) == len(set(덮인턴)), "턴범위가 겹친다"
    assert 덮인턴 == list(range(1, len(덮인턴) + 1)), "중간에 빈 턴이 있다"


def test_시련은_9턴이다():
    """**PRD A-4 「시련 턴 고정」.** 뼈대가 9턴으로 못 박았다."""
    assert 뼈대.시트의("trial").담나(뼈대.시련턴)


def test_경로가_넷이다():
    """**셋이 되면 4경로 동등이 조용히 깨진다.**

    **⚠ 페르소나 2원형(A 이민준 / B 김서윤)이 걸린 자리다** — 한 경로가 빠지면
    그 원형의 아이가 갈 길이 없어진다.
    """
    assert {길.code for 길 in 뼈대.경로들()} == {"force", "persuade", "observe", "care"}


def test_네_경로의_통과서사가_서로_다르다():
    """**⛔ 「정답이 하나인데 가는 길이 넷」이면 동등이 아니다.**

    통과 서사가 같으면 **넷이 같은 결말로 수렴하는 것**이고, 그건 경로가 **꾸밈**이
    된다. 뼈대가 그 점을 따로 못 박아 뒀다.
    """
    서사들 = [길.통과서사 for 길 in 뼈대.경로들()]

    assert len(set(서사들)) == 4


def test_해결조건이_다_비어있지_않다():
    """**GM 이 이걸로 경로를 판별한다** (PRD A-4 MUST). 비면 판별이 즉흥이 된다."""
    for 길 in 뼈대.경로들():
        assert 길.해결조건.strip()


# ── 조건 공개 시점 ──────────────────────────────────────


@pytest.mark.parametrize("턴", [1, 2, 3, 4, 5])
def test_approach_전에는_조건을_안_보여준다(턴: int):
    assert 뼈대.시련조건을_보여주나(턴) is False


@pytest.mark.parametrize("턴", [6, 7, 8, 9, 10])
def test_approach_부터_보여준다(턴: int):
    assert 뼈대.시련조건을_보여주나(턴) is True


# ── 시련을 못 넘은 턴 ───────────────────────────────────


def test_시련을_못_넘으면_10턴에도_trial_이다():
    """**뼈대가 「통과 못 하면 10·11턴으로 밀린다」고 적었다.**

    표만 보고 10턴을 `resolution` 으로 주면 **시련을 못 넘은 아이에게 완결 서사가
    나간다** — 그 아이는 **못 넘었는데 끝난 것**을 본다.
    """
    assert 뼈대.지금비트(10, 시련넘었나=False).beat == "trial"
    assert 뼈대.지금비트(10, 시련넘었나=True).beat == "resolution"


def test_12턴을_넘기지_않는다는_값이_있다():
    """**⏳ 12턴에도 못 넘으면 어떻게 되나는 아직 안 정했다** (뼈대 「열린 것」).

    **값만 있고 귀결이 없다** — 그 결정은 3번(A-4)·5번(D-1)과 같이 내려온다.
    여기서는 **상한이 존재한다는 것**만 박는다.
    """
    assert 뼈대.최대턴 == 12
    assert 뼈대.최대턴 > 뼈대.시련턴
