"""**측정 셋이 스스로 통과해 버리지 않는가** (W5 3번).

**재는 스크립트에 검사를 건다.** 이 파일이 없으면 셋이 조용히 망가진 채로
「미탐 0」을 찍는다 — `W3-ner-fp.md` 가 「오탐 0이 아무것도 안 잰 것과 구분이
안 될 수 있다」로 적어 둔 것과 **같은 종류의 함정**이고, 이번에는 **양성 쪽**에 있다.

**가장 나쁜 자리는 `표적` 이 문장에 없는 사례다.** 「표적이 결과에서 사라졌나」로
채점하는데 애초에 없으면 **아무 일도 안 하고 맞은 것이 된다.**
"""

from app.pii import PII_MASK
from scripts.verify_ner_accuracy import 가려야하는것, 경계, 맞았나, 음성셋


def test_표적이_문장에_실제로_들어_있다():
    """**이 파일이 있는 이유다.** 표적이 문장에 없으면 그 사례는 늘 통과다."""
    엉터리 = [
        f"{사례.출처}/{표}"
        for 사례 in 가려야하는것
        for 표 in 사례.표적
        if 표 not in 사례.문장
    ]

    assert 엉터리 == []


def test_양성_사례에는_표적이_하나_이상_있다():
    """표적이 비면 채점이 「가릴 것이 없다」가 되어 **자동 통과**다."""
    빈것 = [사례.출처 for 사례 in 가려야하는것 if not 사례.표적]

    assert 빈것 == []


def test_경계_사례도_표적이_문장에_있다():
    엉터리 = [f"{사례.출처}/{표}" for 사례 in 경계 for 표 in 사례.표적 if 표 not in 사례.문장]

    assert 엉터리 == []


def test_표적이_사라지면_맞은_것이다():
    assert 맞았나(("김민준",), f"{PII_MASK}이랑 같이 동굴로 들어갔다") is True


def test_표적이_남아_있으면_틀린_것이다():
    assert 맞았나(("김민준",), "김민준이랑 같이 동굴로 들어갔다") is False


def test_표적이_둘이면_둘_다_사라져야_맞은_것이다():
    """**한 문장에 두 사람이 나오는 자리가 실제 위험이다** — 모델이 하나만 돌려주면
    나머지 하나가 그대로 아이 책에 인쇄된다."""
    반만 = f"{PII_MASK}이랑 조은우가 같이 뛰어왔다"

    assert 맞았나(("윤서준", "조은우"), 반만) is False
    assert 맞았나(("윤서준", "조은우"), f"{PII_MASK}이랑 {PII_MASK}가 같이 뛰어왔다") is True


def test_음성은_마스크가_하나라도_있으면_틀린_것이다():
    """음성은 **가리면 안 되는 것**이다 — 무엇을 가렸든 틀린 것이다."""
    assert 맞았나((), "나침이가 은빛 검을 들고 달려갔다") is True
    assert 맞았나((), f"{PII_MASK}가 은빛 검을 들고 달려갔다") is False


def test_음성_셋을_오탐_스크립트에서_그대로_가져온다():
    """**두 벌로 갈라 두지 않는다.** 갈리면 한쪽만 고쳐지고, 그때 두 문서가 서로
    다른 셋을 재면서 같은 이름으로 불린다."""
    from scripts.verify_ner_fp import 문장들

    assert len(음성셋()) == len(문장들())
