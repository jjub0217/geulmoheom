"""챕터 진행 규칙 (A-4 · W7 3번 · `docs/api/Stage1.md` 3·5절).

**⛔ 여기서 새로 정하는 규칙이 없다.** 전부 문서에 있다 —

- **시련은 9턴 고정, 통과 못 하면 10·11턴으로 밀리고 12턴을 넘기지 않는다** (뼈대 비트 시트)
- **G2 이상 1턴 · G1 2턴 · G0 스캐폴딩(턴 미소모)** (PRD 165행 · `Stage1.md` 3절)
- **경로에 따른 차별이 없다 — 등급·삽화 티어·완결 여부 전부** (PRD A-4)
- **12턴에 닿으면 못 넘었어도 완결. 보상은 등급이 정한다** (`문구.md` 1.24 · `Stage1.md` 5절)

**이 파일이 지키는 것은 「네 경로가 각각 완결에 닿는다」**(주차 계획 완료 조건 · 검사 넷)
**와 「그 넷이 동등하다」**다. 뒤엣것이 **페르소나 2원형이 걸린 자리**다.
"""

import pytest

from app import chapter_run as 진행기
from app import chapter_skeleton as 뼈대
from app.chapter_run import 진행

경로넷 = ["force", "persuade", "observe", "care"]


def _approach까지(등급: str = "G2") -> 진행:
    """1턴부터 8턴까지 굴린 진행. **다음 턴이 시련(9턴)이다.**"""
    지금 = 진행()
    for _ in range(8):
        지금 = 진행기.다음(지금, 등급=등급)
    return 지금


# ── 시련 전 ─────────────────────────────────────────────


def test_시련_전에는_등급이_진행을_안_쌓는다():
    """**시련은 9턴 고정이다.** 앞턴에서 잘 쓴 것이 시련을 미리 깎으면
    **9턴이 「고정」이 아니게 되고**, 아이가 **시련에 닿기 전에 이미 이긴 판**이 된다."""
    여덟턴 = _approach까지("G3")

    assert 여덟턴.턴 == 8
    assert 여덟턴.시련진행 == 0
    assert not 여덟턴.시련넘었나
    assert 여덟턴.비트 == "approach"


def test_남은턴은_열두턴에서_센다():
    """`turns_left` 가 매 응답에 실린다 (`Stage1.md` 4절). **12턴을 넘기지 않는다.**"""
    assert 진행().남은턴 == 뼈대.최대턴 == 12
    assert _approach까지().남은턴 == 4


# ── 시련 통과 판정 — 등급이 정한다 ────────────────────────


@pytest.mark.parametrize("등급", ["G2", "G3"])
def test_G2_이상은_한_턴에_넘는다(등급: str):
    """PRD 165행 그대로."""
    아홉턴 = 진행기.다음(_approach까지(), 등급=등급, 경로="observe")

    assert 아홉턴.턴 == 9
    assert 아홉턴.비트 == "trial"
    assert 아홉턴.시련넘었나
    assert 아홉턴.시련경로 == "observe"


def test_G1_은_두_턴이_걸리고_열턴으로_밀린다():
    """**밀리는 것이 실패가 아니다** (뼈대 「통과 못 하면 10·11턴으로 밀린다」).

    **⛔ 턴만 보면 10턴이 `resolution` 이다** — 못 넘은 아이에게 완결 서사가 나간다.
    """
    아홉턴 = 진행기.다음(_approach까지(), 등급="G1", 경로="care")
    assert not 아홉턴.시련넘었나
    assert 아홉턴.비트 == "trial"

    열턴 = 진행기.다음(아홉턴, 등급="G1", 경로="care")
    assert 열턴.턴 == 10
    assert 열턴.비트 == "trial"  # 넘은 턴은 아직 trial 이다. resolution 은 다음 턴
    assert 열턴.시련넘었나


def test_G0_은_되묻고_턴을_안_먹는다():
    """**되묻기가 상한을 깎으면 막힌 아이가 더 빨리 잠긴다** (`Stage1.md` 4절)."""
    여덟턴 = _approach까지()

    assert 진행기.스캐폴딩할까("G0", 선택지로왔나=False)
    그대로 = 진행기.다음(여덟턴, 등급="G0", 선택지로왔나=False)

    assert 그대로 == 여덟턴


def test_선택지로_온_G0_은_되묻지_않고_턴을_먹는다():
    """`Stage1.md` 2절 — **고른 것을 되물으면 뜻이 없다.** 그래도 턴은 지나간다."""
    여덟턴 = _approach까지()

    assert not 진행기.스캐폴딩할까("G0", 선택지로왔나=True)
    아홉턴 = 진행기.다음(여덟턴, 등급="G0", 경로="force", 선택지로왔나=True)

    assert 아홉턴.턴 == 9
    assert not 아홉턴.시련넘었나
    assert 아홉턴.시련진행 == 0


# ── ⭐ 네 경로가 각각 완결에 닿는다 (검사 넷) ──────────────


@pytest.mark.parametrize("경로", 경로넷)
def test_네_경로가_각각_완결에_닿는다(경로: str):
    """**주차 계획의 완료 조건이 이것이다.** 한 판을 1턴부터 끝까지 굴린다.

    **⛔ 「정답이 하나인데 가는 길이 넷」이면 동등이 아니다** (뼈대). 넷이 각각
    **다른 방식으로 같은 곳에 닿는다** — 그래서 네 판을 따로 굴려 본다.
    """
    지금 = 진행기.다음(_approach까지(), 등급="G2", 경로=경로)
    assert 지금.시련넘었나 and not 지금.완결

    완결턴 = 진행기.다음(지금, 등급="G2")

    assert 완결턴.턴 == 10
    assert 완결턴.비트 == "resolution"
    assert 완결턴.완결
    assert 완결턴.시련경로 == 경로


def test_경로가_달라도_턴수와_티어가_같다():
    """**⛔ 여기가 페르소나 2원형이 걸린 자리다** (`Stage1.md` 3절).

    **한 경로가 더 좋은 그림을 받으면 그 원형이 불리해진다** — A 이민준(행동)이
    힘으로, B 김서윤(서사)이 설득으로 넘었을 때 **둘이 같은 것을 받아야 한다.**
    """
    끝 = {}
    for 경로 in 경로넷:
        지금 = 진행기.다음(_approach까지(), 등급="G2", 경로=경로)
        끝[경로] = 진행기.다음(지금, 등급="G2")

    턴수 = {것.턴 for 것 in 끝.values()}
    티어 = {진행기.티어(것) for 것 in 끝.values()}
    완결 = {것.완결 for 것 in 끝.values()}

    assert 턴수 == {10}
    assert 티어 == {"rare"}
    assert 완결 == {True}


# ── 12턴 — 못 넘었어도 완결이다 ──────────────────────────


def test_열두턴에_닿으면_못_넘었어도_완결이다():
    """**⛔ 「못 넘었다」로 끝내지 않는다** (`문구.md` 1.24 · 2026-09-16 PM 판정).

    A-7 이 **「챕터 완결 = 책 한 장」**이라, 못 넘은 것으로 끝내면 **12턴을 다 쓴
    아이만 책이 빈다** — **제일 많이 쓴 아이가 제일 적게 받는다.**
    """
    지금 = _approach까지()
    for _ in range(4):  # 9·10·11·12턴을 선택지 G0 으로 (진행이 안 쌓인다)
        지금 = 진행기.다음(지금, 등급="G0", 경로="force", 선택지로왔나=True)

    assert 지금.턴 == 12
    assert not 지금.시련넘었나
    assert 지금.완결
    assert 지금.남은턴 == 0


def test_열두턴_완결의_보상은_등급이_정한다():
    """**⛔ 그렇다고 똑같지 않다** (`Stage1.md` 5절). **차이는 삽화 티어에서 나지
    완결 여부에서 나지 않는다** — 12턴까지 `G1` 만 낸 아이는 `basic` 이다."""
    지금 = _approach까지()
    for _ in range(3):
        지금 = 진행기.다음(지금, 등급="G1", 경로="care", 선택지로왔나=True)

    # 9턴 G1(1) + 10턴 G1(2 — 넘었다) 이라 11턴은 resolution 이다
    assert 지금.시련넘었나
    assert 진행기.티어(지금) == "basic"


def test_최대턴을_넘기지_않는다():
    """**12턴을 넘기지 않는다** (뼈대). 완결 뒤 또 부르는 자리는 엔드포인트가 막지만,
    **규칙 자체도 넘지 않아야** 한 군데만 고쳐도 되는 자리가 생긴다."""
    지금 = _approach까지()
    for _ in range(9):
        지금 = 진행기.다음(지금, 등급="G0", 경로="force", 선택지로왔나=True)

    assert 지금.턴 == 뼈대.최대턴
    assert 지금.남은턴 == 0
