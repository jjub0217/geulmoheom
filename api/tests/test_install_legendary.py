"""**어느 파일을 넣나** — 선정 목록 읽기 (W5 7번 ③).

**목록을 우리가 고르지 않는다.** `docs/삽화_legendary_선정.md` 가 PM 검수 결과이고
**그 문서가 SSOT** 다. 여기서 재는 것은 **문서에 적힌 그대로 읽는가** 하나다.

**⚠ 「최신 회차를 자동으로 고른다」가 틀리는 자리가 실제로 있다.** `c02` 만
**가운데 회차(`수리2차`)**를 쓴다 — 최신(`수리3차`)은 동굴 벽 기호가 문자로 읽히고,
최초 전수판은 가이드가 화면을 절반 넘게 먹는다. **둘 다 피한 것이 가운데 하나뿐**이라
자동 선택은 여기서 조용히 틀린다.
"""

import pytest

from scripts.install_legendary import 선정목록


def test_열여덟_장을_읽는다():
    """**20장이 아니다.** `c10`·`c12` 는 쓸 수 있는 판이 없어 빠졌고, 그 두 카드의
    6조합은 기본 에셋으로 간다."""
    assert len(선정목록()) == 18


def test_c02_는_가운데_회차다():
    """**이 파일이 있는 이유다.** 최신을 고르면 여기서 틀린다."""
    assert 선정목록()["c02"] == "수리2차/c02.jpg"


def test_재생성으로_표시된_카드는_안_들어간다():
    목록 = 선정목록()

    assert "c10" not in 목록
    assert "c12" not in 목록


def test_읽은_파일이_실제로_있다():
    """문서가 가리키는 것과 디스크가 어긋나면 **넣는 시점이 아니라 여기서** 드러난다.

    **원본이 없는 기계에서는 건너뛴다 — 잴 대상이 없기 때문이다.** `api/out/` 은
    `.gitignore` 라 **그 기기에만 있고**(`adr/0012` 따라오는 작업 ⑤) CI 컨테이너에는
    아예 없다. 2026-09-14 에 CI 가 살아나자마자 이 검사가 18장을 「없다」로 물었다.

    **⛔ 조건을 「CI 면 건너뛴다」로 적지 않는다.** 그렇게 적으면 검사가 **로컬 전용**이
    되고, 그건 `alembic check` 을 CI 에만 붙였을 때와 **같은 실패의 반대 방향**이다 —
    한쪽에만 있으면 다른 쪽에서 안 막는다. **조건은 장소가 아니라 대상이다** —
    원본 뿌리가 있으면 CI 든 남의 기계든 잰다. 원본을 받아 두는 날 CI 에서도 저절로 켜진다.

    **이 검사의 본체는 「넣기 직전」이다.** `install_legendary.py` 를 돌리는 기계에는
    원본이 반드시 있으므로 **거기서는 건너뛰지 않는다.** 문서와 디스크가 갈린 채로
    넣으면 **스크립트가 조용히 건너뛰고 아이 화면은 기본 에셋으로 간다** — 빨간불이
    아니라 「그림이 밋밋하다」로 나타나는 부류라, 넣기 전에 잡아야 하는 것이 맞다.
    """
    from scripts.install_legendary import 원본뿌리

    if not 원본뿌리.is_dir():
        pytest.skip(f"원본이 없는 기계다 — {원본뿌리} 가 없어 대조할 대상이 없다")

    없는것 = [카드 for 카드, 상대 in 선정목록().items() if not (원본뿌리 / 상대).is_file()]

    assert 없는것 == []
