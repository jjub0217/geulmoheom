"""챕터 진행 규칙 (A-4 · W7 3번). **규칙은 문서에 있고 여기는 그것을 굴린다.**

**⛔ 새로 정하는 것이 없다.**

| 규칙 | 어디에 |
|---|---|
| 시련 9턴 고정 · 밀리면 10·11턴 · **12턴을 넘기지 않는다** | `docs/챕터뼈대_초안.md` 비트 시트 |
| **G2 이상 1턴 · G1 2턴 · G0 스캐폴딩(턴 미소모)** | `MVP_PRD.md` 165행 · `Stage1.md` 3절 |
| **경로에 따른 차별 없음 — 등급·티어·완결 전부** | PRD A-4 · `Stage1.md` 3절 |
| **12턴에 닿으면 못 넘었어도 완결. 보상은 등급** | `문구.md` 1.24 · `Stage1.md` 5절 |
| 비트·핵심 씬·네 경로의 해결 조건 | `chapter_skeleton.py` (문서에서 읽는다) |

**⛔ 왜 순수 함수인가.** 진행 규칙이 엔드포인트 안에 있으면 **한 판을 끝까지 굴려
보려면 DB 와 GM 호출이 필요해진다.** 그러면 **네 경로를 각각 끝까지 굴리는 검사
넷**(주차 계획 완료 조건)이 **유료 호출 넷**이 된다. 여기는 **상태를 받아 다음 상태를
돌려주기만** 하고, 저장은 2번(A-2)이, GM 호출은 1번(A-1)이 한다.

**⛔ 「보스」를 쓰지 않는다** (`용어사전.md` 8장). 비트 값은 `trial` 이고 경로는
`force`·`persuade`·`observe`·`care` 다 — **식별자에도 안 쓴다.**

**⛔ 티어 표를 다시 만들지 않는다** — `evaluator.TIER_BY_GRADE` 그대로다. 두 군데
두면 **Stage 0 과 Stage 1 의 보상이 갈리고**, 갈린 쪽이 아이에게 간다.
"""

from dataclasses import dataclass, replace
from typing import Final

from app import chapter_skeleton as 뼈대
from app.evaluator import TIER_BY_GRADE
from app.schemas.stage0 import Tier
from app.schemas.stage1 import Beat, TrialPath

# **G2 이상이면 한 턴, G1 은 두 턴** (PRD 165행). 걸음을 둘·하나로 두고 문턱을 둘로
# 잡으면 그 문장이 그대로 코드가 된다 — **분기를 늘리지 않는다.**
통과문턱: Final = 2
# **뼈대가 정한다** — 여기서 숫자를 두 번 적지 않는다
최대턴: Final = 뼈대.최대턴
_걸음: Final[dict[str, int]] = {"G3": 2, "G2": 2, "G1": 1, "G0": 0}


@dataclass(frozen=True)
class 진행:
    """한 챕터의 진행. **아이 원문이 여기 없다** — 원문은 책 콘텐츠다 (PRD 1.1b).

    **`시련최고등급` 을 쥐는 이유는 보상이다.** 12턴까지 `G1` 만 낸 아이는 `basic`
    이고, **차이는 삽화 티어에서 나지 완결 여부에서 나지 않는다** (`Stage1.md` 5절).
    """

    턴: int = 0
    # **⛔ 비트를 나중에 계산하지 않고 턴과 함께 굳힌다** (2026-09-16 검사가 짚었다).
    # 나중에 계산하면 **10턴에 시련을 넘은 아이의 그 턴이 `resolution` 으로 보인다** —
    # 그 턴의 서사는 **통과 서사**이고 `trial` 이다. 비트는 **그 턴을 쓸 때 무엇이었나**지
    # **쓰고 난 뒤 무엇이 됐나**가 아니다.
    비트: Beat = "intro"
    시련진행: int = 0
    시련경로: TrialPath | None = None
    시련최고등급: str | None = None

    @property
    def 시련넘었나(self) -> bool:
        return self.시련진행 >= 통과문턱

    @property
    def 완결(self) -> bool:
        """**둘 중 하나면 완결이다** — 완결 비트에 닿았거나, **12턴에 닿았거나.**

        뒤엣것이 2026-09-16 PM 판정이다. **「못 넘었다」로 끝내면 A-7 에서
        12턴을 다 쓴 아이만 책이 빈다.**
        """
        return self.비트 == "resolution" or self.턴 >= 뼈대.최대턴

    @property
    def 남은턴(self) -> int:
        return max(0, 뼈대.최대턴 - self.턴)

    @property
    def 핵심씬(self) -> bool:
        """삽화를 굽는 턴인가. **뼈대가 정하고 모델이 안 정한다** — 돈이다."""
        return 뼈대.핵심씬인가(self.턴)


def 스캐폴딩할까(등급: str, *, 선택지로왔나: bool) -> bool:
    """G0 이면 되묻는다 (PRD 4.4). **다만 선택지로 온 턴은 안 되묻는다** —
    **고른 것을 되물으면 뜻이 없다** (`Stage1.md` 2절)."""
    return 등급 == "G0" and not 선택지로왔나


def 다음(
    지금: 진행,
    *,
    등급: str,
    경로: TrialPath | None = None,
    되물었나: bool = False,
) -> 진행:
    """턴 하나를 굴린다.

    **⛔ 되묻는 턴은 턴을 안 먹는다** — 되묻기가 상한을 깎으면 **막힌 아이가 더 빨리
    잠긴다** (`Stage1.md` 4절). 그래서 **같은 진행을 그대로 돌려준다.**

    **⛔ 「되물었나」를 등급에서 유추하지 않는다** (2026-09-16에 고쳤다). 유추하면
    **되묻기가 실패한 날 턴이 영원히 안 는다** — Redis 를 못 세면 `되묻기횟수()` 가
    `None` 을 주고 그때는 **되묻지 않고 G1 취급으로 지나가야 한다**(PRD A-5).
    그 판단은 **되물어 봤는지를 아는 부르는 쪽**에 있다.

    **⛔ 시련 진행은 시련 비트에서만 쌓인다.** 앞턴에서 잘 쓴 것이 시련을 미리 깎으면
    **9턴이 「고정」이 아니게 되고**, 아이가 **시련에 닿기 전에 이미 이긴 판**이 된다.

    **경로는 마지막에 디딘 것을 남긴다.** G1 로 두 턴에 넘을 때 아이가 길을 바꿀 수
    있고, **통과 서사는 마지막 경로의 것**이다 (뼈대 「통과」 열).
    """
    if 되물었나:
        return 지금
    if 지금.완결:
        # **12턴을 넘기지 않는다** (뼈대). 엔드포인트가 먼저 막지만 **규칙 자체도
        # 넘지 않아야** 고칠 자리가 한 군데로 남는다.
        return 지금

    새턴 = 지금.턴 + 1
    # **다음 턴의 비트로 판단한다** — 지금 비트가 아니다. 8턴에서 부르면 아이가
    # 쓰는 것은 9턴(`trial`)이고, 그 등급이 시련에 걸린다.
    비트 = 뼈대.지금비트(새턴, 시련넘었나=지금.시련넘었나).beat
    if 비트 != "trial":
        return replace(지금, 턴=새턴, 비트=비트)

    걸음 = _걸음[등급]
    return replace(
        지금,
        턴=새턴,
        비트=비트,
        시련진행=min(통과문턱, 지금.시련진행 + 걸음),
        시련경로=경로 if 걸음 and 경로 else 지금.시련경로,
        시련최고등급=_더높은등급(지금.시련최고등급, 등급),
    )


def 티어(지금: 진행) -> Tier:
    """이 챕터의 보상 티어. **`evaluator.TIER_BY_GRADE` 를 그대로 쓴다.**

    **⛔ 경로가 티어를 안 바꾼다** (PRD A-4). **설득으로 넘은 시련도 힘으로 넘은 것과
    같은 티어**다 — 한 경로가 더 좋은 그림을 받으면 **페르소나 2원형 중 하나가
    불리해진다.**
    """
    return TIER_BY_GRADE[지금.시련최고등급 or "G0"]


def _더높은등급(있던것: str | None, 새것: str) -> str:
    """**시련에서 낸 것 중 가장 높은 등급.** 보상은 등급이 정하고, **여러 턴에 걸쳐
    넘은 아이를 낮은 턴 하나로 깎지 않는다.**"""
    if 있던것 is None:
        return 새것
    return max(있던것, 새것)  # "G0" < "G1" < "G2" < "G3" — 문자열 순서가 등급 순서다


def 첫상태() -> dict[str, object]:
    """새 판의 상태 (PRD 4.2 의 부분집합).

    **⛔ 여기서 규칙을 만들지 않았다.** 체력은 **PRD 4.2 예시가 `max_hp: 10`** 이라
    시작을 꽉 찬 값으로 뒀고, 위치는 **뼈대 1턴의 「광장에 닿으니」**에서 왔다.
    **⚠ 체력을 깎는 규칙은 아직 어디에도 없다** — 있으면 그때 여기가 아니라 문서가 먼저다.

    **⛔ 아이 닉네임을 넣지 않는다.** `children.nickname` 에 이미 있고, 여기 복사하면
    **한 값이 두 군데 살면서 지울 때 한쪽만 지워진다** (E-5 파기가 그 자리다).

    **⏳ `summary`·`recent_turns`·`grades` 는 2번(A-2)이 더한다** — `recent_turns` 에는
    **아이 원문**이 들어가므로, 그 자리는 **원문을 어디에 두는가**를 정하고 나서다.
    """
    return {
        "hero": {"hp": 10, "max_hp": 10, "items": [], "skills": []},
        "location": "마을 광장",
        "npcs": [],
    }


def 챕터제목() -> str:
    """완결 화면의 제목 (계약 5절). **뼈대 문서에서 읽는다** — 코드에 안 박는다."""
    return 뼈대.챕터제목()
