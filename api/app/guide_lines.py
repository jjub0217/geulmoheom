# 1.20 안의 「대표 그림 상태」 표. 표 모양이라 `_대사줄`(인용문)에 안 걸린다.
_그림상태줄 = re.compile(r"^\|\s*(?P<상태>준비됨|준비 중)\s*\|\s*\*\*(?P<문장>.+?)\*\*\s*\|\s*$")


@lru_cache
def 완결대사_그림() -> dict[str, str]:
    """완결 안내 중 **대표 그림 상태를 보고 고르는 두 줄** (`문구.md` 1.20 · 2026-09-20).

    **⛔ 위 `완결대사()` 와 같은 절인데 모양이 다르다.** 저쪽은 인용문 묶음에서
    무작위로 하나를 고르고, 이쪽은 **표에서 상태로 하나를 집는다** — 그래서 읽는
    함수가 따로다.

    **⛔ 코드에 문장을 복사하지 않는 이유가 여기서 값을 했다.** 2026-09-20 에 이 두
    줄이 `api/v1/stage1.py` 에 박힌 채로 들어갔고, **검사는 옛 `완결대사()` 만 보고
    있어 한 판을 끝까지 굴리는 검사가 빨개졌다.** 문서 한 곳에서 읽으면 갈라지지
    않는다.
    """
    묶음 = {맞음["상태"]: 민(맞음["문장"]) for 줄 in _절(완결) if (맞음 := _그림상태줄.match(줄))}
    if set(묶음) != {"준비됨", "준비 중"}:
        raise RuntimeError(
            "문구.md 1.20 의 대표 그림 상태 표를 못 읽었다. 표 모양이 바뀌었는지 본다"
        )
    return 묶음


