from functools import lru_cache
from typing import Final, Literal

from app.config import REPO_ROOT
from app.docs_md import 민, 읽기
from app.schemas.stage0 import Tier

문구문서 = REPO_ROOT / "docs" / "문구.md"

# `> 1. **문장**` 꼴만 읽는다. 같은 절의 「지킬 것」은 `-` 로 시작해 여기 안 걸린다.
_대사줄 = re.compile(r"^>\s*\d+\.\s*(?P<문장>.+?)\s*$")

# 절 제목. **번호로 찾지 않는다** — `문구.md` 는 절 순서가 번호 순이 아니다(1.9 가 1.8
# 앞에 있다). 제목 앞부분으로 맞춘다.
# **1.5(삽화 대기)는 여기 없다.** 그 대사가 뜨는 6~8초는 폴링 중이라 오는 응답이
# `Artwork` 뿐이고 `guide` 가 없다 (`Stage0.md` 5절) — 서버가 내려줄 자리가 아예 없어
# 프론트가 `web/src/components/artwork-copy.ts` 에 옮겨 뒀다. **읽는 코드를 여기 두면
# 아무도 안 부르는 채로 남는다.**
# 1.4b 는 **문장이 하나**다. 티어도 무작위도 없어 고르지 않는다.
카드첫말_절 = "### 1.4b"
결과 = "### 1.6"
종료 = "### 1.10"
차단 = "### 1.11"
완결 = "### 1.20"
자해 = "### 1.2 "  # **뒤 공백이 있다** — 없으면 `1.20`·`1.21` 이 먼저 걸린다
복귀 = "### 1.23"

# 1.6 안에서 티어를 가르는 소제목. 문서가 코드 식별자를 함께 적어 둬서 그것으로 맞춘다 —
# 「기본」이라는 낱말로 맞추면 「지킬 것」의 「기본에도 「부족하다」가 없다」에 걸린다.
_티어표시: Final[dict[str, Tier]] = {
    "`basic`": "basic",
    "`rare`": "rare",
    "`legendary`": "legendary",
}


def _절(제목: str) -> list[str]:
    """그 `###` 절의 줄들. 다음 `###` 에서 끊는다."""
    줄들: list[str] = []
    안에 = False
    for 줄 in 읽기(문구문서).splitlines():
        if 줄.startswith("### "):
            안에 = 줄.startswith(제목)
            continue
        if 안에:
            줄들.append(줄)
    return 줄들


def _대사들(줄들: list[str]) -> list[str]:
    return [민(맞음["문장"]) for 줄 in 줄들 if (맞음 := _대사줄.match(줄))]


@lru_cache
def 카드첫말() -> str:
    """카드 화면에서 가이드가 거는 첫 말 (`문구.md` 1.4b).

    **이 자리가 문서에 없었다** (2026-09-09 신설). 화면에 그대로 나가는 문장인데
    **픽스처와 `Stage0.md` 예시에만 살아 있었고**, 그래서 **문서를 고쳐도 화면이
    안 따라왔다** — `문구.md` 0장 「목·픽스처도 이 문서를 읽는다」의 그 부류다.

    **하나뿐이라 고르지 않는다.** 「여기 이 나침반」의 **「여기 이」가 지시어**라
    아이가 화면에서 그 원을 찾는 것이 이 문장의 전부다.
    """
    for 줄 in _절(카드첫말_절):
        if 줄.startswith(">"):
            return 민(줄.lstrip("> "))
    raise RuntimeError("문구.md 1.4b 에서 대사를 못 읽었다. 절 모양이 바뀌었는지 본다")


@lru_cache
def 일일카드종료대사() -> str:
    """일일 카드 종료의 고정 배웅 (`문구.md` 1.10).

    챕터는 완결해야 책에 쌓이므로, 턴 상한에 쓰는 번호 대사와 분리한다.
    """
    for 줄 in _절(종료):
        if 줄.startswith(">") and not _대사줄.match(줄):
            return 민(줄.lstrip("> "))
    raise RuntimeError("문구.md 1.10 에서 카드 종료 대사를 못 읽었다. 절 모양을 확인한다")


