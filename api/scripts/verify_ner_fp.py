"""E-2 후속 — 실명 검사 **오탐 셋** (W4 13번). **프리테스트보다 먼저 선다.**

**재는 것은 오탐 하나뿐이다.** 판타지 이름이 서버에서 가려지는지만 본다.
**미탐은 안 잰다** — 아동 3명에서 실물이 안 나오고(자해 분기가 「테스트로만 서 있다」와
같은 자리), 전체 정확도는 W5 다.

**합격선: 오탐 0.** 하나라도 가려지면 그 자리는 **아이가 지은 이름이 `○○○` 로 바뀌어
자기 책에 인쇄되는 것**이다. 그리고 아이는 **왜 그렇게 됐는지 못 듣는다** — 차단이
아니라 마스킹이라 화면에 아무 말도 안 나온다 (미결 11-5).

**문장은 지어내지 않는다.** `docs/장면카드_초안.md` **검수본 20장**의 상황문과 명사
태그에서 뽑는다 — **새로 지어내면 우리가 상상한 오탐만 잡는다** (W4 계획).
여기에 더하는 것은 **가이드 이름과 괴물 이름** 셋뿐이고, 그건 아이가 실제로 짓는
자리다 (`app/accounts.py` 가이드 이름 · `bench_ner.py` 가 이미 쓰던 값).

**운영 코드를 그대로 태운다** — `app.pii.실명까지가리기`. 스크립트가 자기 호출을
따로 짜면 **여기서만 통과하고 제품에서는 가려진다** (`verify_safety.py` 와 같은 이유).

실행: `PYTHONPATH=. uv run python scripts/verify_ner_fp.py`
"""

import asyncio
import sys

from app.pii import PII_MASK, 실명까지가리기
from app.scene_cards import 모험카드들

# 아이가 짓는 이름들. **가장 헷갈리는 자리다** — 사람 이름과 글자 수·모양이 같다.
# 「나침이」는 가이드 기본 이름이고(`docs/용어사전.md`), 나머지 둘은 괴물 이름이다.
#
# **`제외` 에 넣지 않고 태운다.** 서버는 자녀 닉네임과 가이드 이름을 알아서 빼 주는데
# (`실명까지가리기(제외=...)`), 그 장치에 기대면 **아이가 문장 안에서 새로 지은 이름**은
# 못 잡는다. 여기서 보려는 것이 바로 그 자리다.
지은이름 = ["나침이", "크라운", "그림자늑대"]

# **대조군.** 실명이 실제로 가려지는지 본다 — 이게 안 가려지면 **NER 이 죽은 것**이고,
# 그때 「오탐 0」은 통과가 아니라 **아무것도 안 잰 것**이다. `실명까지가리기()` 는
# 뒷단이 죽어도 예외를 안 내고 정규식 결과로 조용히 진행한다(아이를 막지 않으려고) —
# **그 관대함이 이 측정을 통째로 무의미하게 만들 수 있는 자리**라 대조군을 둔다.
# 지어낸 이름이다. 실제 아동 문장이 아니다 (PRD 1.1b).
대조군 = "김민준이랑 같이 동굴로 들어갔다"

# 카드에서 뽑은 대상에 붙일 틀. **행동 문장이어야 한다** — 목록으로 던지면 모델이
# 개체명 나열로 읽어 실제 입력과 다른 조건이 된다.
틀 = "{말}을 한참 살펴보다가 조심스럽게 다가갔다"


def 문장들() -> list[tuple[str, str]]:
    """`(출처, 문장)`. **상황문 원문과 태그 문장을 둘 다 태운다.**

    상황문은 아이가 읽는 장면이고, 태그 문장은 아이가 쓸 법한 문장이다. 오탐은
    **문장 모양에 따라 다르게 난다** — 한쪽만 재면 다른 쪽이 안 보인다.
    """
    묶음: list[tuple[str, str]] = []
    for 카드 in 모험카드들():
        묶음.append((f"{카드.card_id} 상황문", 카드.상황문))
        if 카드.대상:
            묶음.append((f"{카드.card_id} 태그", 틀.format(말=카드.대상)))

    for 이름 in 지은이름:
        묶음.append((f"지은이름 {이름}", f"{이름}이 은빛 검을 들고 앞장서서 걸어갔다"))
    return 묶음


async def 한번(출처: str, 문장: str) -> tuple[str, str, bool]:
    # **`제외` 를 비운다.** 서버가 아는 값으로 빼 주는 길을 막고 **모델이 그냥
    # 흘려보내는지**를 본다 — 그것이 이 셋이 재려는 것이다.
    가려진, _ = await 실명까지가리기(문장, 제외=())
    return 출처, 가려진, PII_MASK in 가려진


async def main() -> None:
    셋 = 문장들()
    결과, (_, 가려진대조, 대조걸림) = await asyncio.gather(
        asyncio.gather(*(한번(출처, 문장) for 출처, 문장 in 셋)),
        한번("대조군", 대조군),
    )

    if not 대조걸림:
        # **먼저 죽는다.** 여기를 통과로 읽으면 다음 사람이 「오탐 0」만 보고 넘어간다.
        print(f"대조군이 안 가려졌다 — NER 이 안 돌고 있다\n  {가려진대조}")
        sys.exit(2)

    오탐 = [(출처, 가려진) for 출처, 가려진, 걸림 in 결과 if 걸림]

    print(f"실명 검사 오탐 셋 — {len(셋)}문장 (카드 20장 + 지은 이름 {len(지은이름)})")
    print("대조군: 실명이 가려졌다 — NER 이 돌고 있다\n")
    for 출처, 가려진 in 오탐:
        print(f"  오탐  {출처}\n        {가려진}")

    print(f"\n오탐 {len(오탐)}/{len(셋)} · 합격선 0")
    if 오탐:
        # **0 이 아니면 실패다.** 프리테스트 선행이라 여기서 멈춘다.
        sys.exit(1)
    print("통과 — 판타지 이름이 서버에서 안 가려진다")


def _NER_이_켜져_있어야_한다() -> None:
    """**꺼진 채로 돌면 「미탐 0」이 통과가 아니라 아무것도 안 잰 것이다.**

    2026-09-09 대표 판정으로 `pii_ner_enabled` 기본값이 꺼짐이 됐다
    (`app/config.py`). 이 스크립트는 **운영 코드를 그대로 태우므로**, 꺼져 있으면
    정규식 결과만 받고 **초록으로 끝난다.** 이 파일이 대조군을 두는 이유와 같은
    함정이라 **자동으로 켜지 않는다** — 켜는 것은 사람이 정한다.
    """
    from app.config import get_settings

    if not get_settings().pii_ner_enabled:
        raise SystemExit(
            "실명(NER)이 꺼져 있다 — 이대로 돌리면 아무것도 안 잰 채 초록이 뜬다.\n"
            "재려면 켜서 돌린다:  PII_NER_ENABLED=1 uv run python -m scripts.verify_ner_fp"
        )


if __name__ == "__main__":
    _NER_이_켜져_있어야_한다()
    asyncio.run(main())
