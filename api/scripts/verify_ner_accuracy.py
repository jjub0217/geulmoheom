def 맞았나(표적: tuple[str, ...], 가려진: str) -> bool:
    """표적이 있으면 **전부 사라져야** 맞은 것, 없으면 **아무것도 안 가려져야** 맞은 것."""
    if not 표적:
        return PII_MASK not in 가려진
    return all(표 not in 가려진 for 표 in 표적)


class _죽었나세기(logging.Handler):
    """**호출 실패와 모델 미탐을 가른다.** `실명까지가리기()` 는 뒷단이 죽어도
    예외를 안 내고 정규식 결과로 진행한다 — 그래서 **밖에서 보면 「모델이 못 잡았다」와
    똑같이 생겼다.** `app/pii.py` 가 그 자리에 남기는 `ner_unavailable` 을 센다.
    """

    def __init__(self) -> None:
        super().__init__()
        self.실패: list[str] = []

    def emit(self, record: logging.LogRecord) -> None:
        if record.getMessage() == "ner_unavailable":
            self.실패.append(getattr(record, "exc_type", "?"))


@dataclass
class 결과:
    사례들: list[사례] = field(default_factory=list)
    틀린것: list[tuple[사례, str]] = field(default_factory=list)

    @property
    def 맞은수(self) -> int:
        return len(self.사례들) - len(self.틀린것)


# **한꺼번에 던지지 않는다.** 61건을 통째로 `gather` 하면 3초 상한(`app.pii.NER_TIMEOUT`)
# 을 넘는 호출이 나고, 그러면 **모델 정확도가 아니라 우리가 만든 동시성을 재게 된다.**
# 2026-09-09 에 실제로 밟았다 — 2회차에서 `TimeoutError` 1건이 나 위 가드가 죽였다.
# **운영은 아이 한 명당 한 번**이라 이 모양이 아니다.
동시 = 8


async def _한번(하나: 사례, 문: asyncio.Semaphore) -> tuple[사례, str]:
    # **`제외` 를 비운다.** 서버는 자녀 닉네임·가이드 이름을 알아서 빼 주는데
    # (`실명까지가리기(제외=...)`), 그 장치에 기대면 **모델 자체의 정확도**가 안 보인다.
    async with 문:
        가려진, _ = await 실명까지가리기(하나.문장, 제외=())
    return 하나, 가려진


async def _재기(사례들: list[사례], 문: asyncio.Semaphore) -> 결과:
    나온것 = await asyncio.gather(*(_한번(하나, 문) for 하나 in 사례들))
    묶음 = 결과(사례들=사례들)
    for 하나, 가려진 in 나온것:
        if not 맞았나(하나.표적, 가려진):
            묶음.틀린것.append((하나, 가려진))
    return 묶음


def _찍기(제목: str, 묶음: 결과) -> None:
    전체 = len(묶음.사례들)
    비율 = 묶음.맞은수 / 전체 * 100 if 전체 else 0.0
    print(f"\n{제목} — {묶음.맞은수}/{전체} ({비율:.1f}%)")
    for 하나, 가려진 in 묶음.틀린것:
        print(f"  ✗ {하나.출처}\n      {가려진}")


async def main() -> None:
    세기 = _죽었나세기()
    logging.getLogger("app.pii").addHandler(세기)

    문 = asyncio.Semaphore(동시)
    실명 = await _재기(_실명, 문)
    정규식 = await _재기(_정규식, 문)
    음성 = await _재기(음성셋(), 문)
    관찰 = await asyncio.gather(*(_한번(하나, 문) for 하나 in 경계))

    if 세기.실패:
        # **먼저 죽는다.** 이 숫자를 문서에 남기면 「미탐 n건」이 실은 「호출이 n번
        # 실패했다」인 채로 굳는다 — W3 이 대조군으로 막은 것과 같은 함정의 양성판이다.
        print(f"\n⛔ NER 호출이 {len(세기.실패)}번 실패했다 ({', '.join(sorted(set(세기.실패)))})")
        print("   정확도를 찍지 않는다 — 반만 잰 숫자가 문서에 남는 것이 제일 나쁘다")
        sys.exit(2)

    _찍기("① 미탐 — 실명 (NER 몫)", 실명)
    _찍기("② 미탐 — 전화·이메일·주소·학교 (정규식 몫)", 정규식)
    _찍기("③ 오탐 — 가리면 안 되는 것", 음성)

    print("\n④ 경계 — 판정에서 뺀다. 관찰만 적는다")
    for 하나, 가려진 in 관찰:
        가려짐 = "가려졌다  " if PII_MASK in 가려진 else "안 가려졌다"
        print(f"  {가려짐} {하나.출처}: {가려진}")

    전체수 = len(실명.사례들) + len(정규식.사례들) + len(음성.사례들)
    맞은수 = 실명.맞은수 + 정규식.맞은수 + 음성.맞은수
    print(
        f"\n전체 정확도 {맞은수}/{전체수} ({맞은수 / 전체수 * 100:.1f}%) · 경계 {len(경계)}건 제외"
    )
    print("NER 호출 실패 0건 — 위 숫자는 모델이 실제로 답한 결과다")


def _NER_이_켜져_있어야_한다() -> None:
    """**꺼진 채로 돌면 「미탐 0」이 통과가 아니라 아무것도 안 잰 것이다.**

    **2026-09-16 대표 판정으로 `pii_ner_enabled` 기본값이 다시 켜짐이 됐다**
    (`app/config.py` · A-7 로 아이 책이 기기 밖에 나간다). 그래서 **보통은 이 관문이
    그냥 통과한다** — 그래도 남겨 둔다: 이 스크립트는 **운영 코드를 그대로 태우므로**
    누군가 꺼 두면 정규식 결과만 받고 **초록으로 끝난다.** 이 파일이 대조군을 두는
    이유와 같은 함정이라 **자동으로 켜지 않는다** — 켜는 것은 사람이 정한다.
    """
    from app.config import get_settings

    if not get_settings().pii_ner_enabled:
        raise SystemExit(
            "실명(NER)이 꺼져 있다 — 이대로 돌리면 아무것도 안 잰 채 초록이 뜬다.\n"
            "재려면 켜서 돌린다:  PII_NER_ENABLED=1 uv run python -m scripts.verify_ner_accuracy"
        )


if __name__ == "__main__":
    _NER_이_켜져_있어야_한다()
    asyncio.run(main())
