/**
 * **아이가 들어와서 보호자 로그인이 풀렸는가** (`문구.md` **3.11**, 2026-09-15 신설).
 *
 * **아이가 같은 기기로 들어오면 서버가 보호자 쿠키를 지운다** (`adr/0014` 결정 3, 비대칭 세션).
 * **그런데 열려 있던 학부모 화면은 그것을 모른다** — 2026-09-14 회차 준비에서 사용자가
 * **되돌릴 수 없는 자녀 삭제 확인창을 다 띄우고 나서야** 403 을 만났다.
 * **왜 안 되는지도, 아이 때문이라는 것도 화면이 말하지 않았다.**
 *
 * ## 왜 주소에 표식인가
 *
 * **`lib/kicked.ts` 와 같은 수법이고 같은 이유**다 — **쿠키가 `HttpOnly` 라 JS 는 세션을
 * 못 본다.** 로그인 화면이 「왜 여기 왔는지」를 아는 길은 **누가 보냈는지**뿐이다.
 *
 * ## ⛔ 이 표식이 없으면 화면이 거짓을 말한다
 *
 * 3.10 로그인 화면의 안내 한 줄은 **「안전을 위해 일정 시간이 지나면 로그아웃됩니다.」**인데,
 * **이 경우 원인은 시간이 아니다.** 그대로 두면 부모가 **「2시간이 지났나 보다」**로 읽고,
 * **다음에 또 같은 일을 겪는다.**
 *
 * ## 아이 쪽 표식과 갈리는 점
 *
 * | | `kicked.ts` (아이) | 여기 (학부모) |
 * |---|---|---|
 * | 언제 단다 | **401** — 들어와 있다가 끊겼다 | **403** — 쿠키가 지워지고 **아이 것이 들어왔다** |
 * | 확신의 근거 | 「그 자리에 오려면 들어와 있었어야 한다」 | **403 자체가 근거다** — 다른 역할의 쿠키가 있다는 뜻이라 **추측이 아니다** |
 *
 * **그래서 이쪽은 「확신이 있는 자리에만 단다」를 따로 따질 게 없다.** 403 이 온 자리면 어디서든
 * 참이다 — 목록이든 삭제든 재발급이든.
 */

/** 주소에 붙이는 표식. **값은 안 본다 — 있으면 아이가 들어온 것이다.** */
export const 아이입장표식 = "child_entered";

/** 403 을 만난 학부모 화면이 보낼 곳. **3.10 화면을 그대로 쓰고 안내 한 줄만 갈린다.** */
export const 아이입장으로보낼곳 = `/parents/login?${아이입장표식}=1`;

/**
 * **정적 빌드라 `useSearchParams` 를 쓰지 않는다** (`lib/kicked.ts` 와 같은 이유).
 * `output: "export"` 에서 그 훅은 `Suspense` 경계를 요구해 **이 한 줄 때문에 화면 구조가 바뀐다.**
 *
 * **효과 안에서 한 번 읽는다** — 렌더 중에 읽으면 첫 HTML 과 하이드레이션이 어긋난다.
 */
export function 아이가들어와서왔나(): boolean {
  if (typeof location === "undefined") return false;
  return new URLSearchParams(location.search).has(아이입장표식);
}
