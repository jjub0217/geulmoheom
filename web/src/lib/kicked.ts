/**
 * **쓰다가 끊겨서 인증 화면으로 왔는가** (`문구.md` **3.3**, 2026-09-12 신설).
 *
 * 화면은 이걸 알아야 **「부모님이 새 접속 코드를 받으셨어요」**를 말할 수 있다. 그런데
 * **쿠키가 `HttpOnly` 라 JS 는 세션을 못 본다.** 남는 길은 **누가 보냈는지**뿐이다.
 *
 * ## 왜 「출처」로 아는가 — 그리고 어디서는 안 다는가
 *
 * **401 이 온 자리가 이미 인증된 화면이면, 그 아이는 들어와 있었다.** 그게 「끊겼다」의 정의다.
 *
 * | 자리 | 다나 | 왜 |
 * |---|---|---|
 * | `POST /attempts` 401 | **단다** | 카드를 받아 쓰고 있었다 — **확실히 들어와 있었다** |
 * | `GET /book` 401 | **단다** | 내 책을 열었다 — 같다 |
 * | `/` 마운트 401 | **⛔ 안 단다** | **처음 온 아이도 여기로 온다.** `start_url` 이 `/` 라 |
 * | 「나가기」 | **⛔ 안 단다** | **아직 부모가 새 코드를 받지 않았다 — 그 문장이 거짓이 된다.** |
 *
 * **틀리는 방향이 대칭이 아니다** — `실행형태판정` 과 같은 잣대다.
 * - 끊겼는데 기본 안내를 보면 → **오늘과 같다.** 나빠지지 않는다
 * - 안 끊겼는데 이 줄을 보면 → **아이에게 거짓을 말한다.** 처음 온 아이가
 *   「부모님이 새 코드를 받으셨어요」를 읽고 **받은 적 없는 코드를 찾는다**
 *
 * **그래서 확신이 있는 자리에만 단다.**
 *
 * ## ⚠ 이것이 덮지 못하는 자리 하나 — 알고 둔다
 *
 * **앱을 껐다 켠 뒤**(재발급된 상태)는 **마운트 401** 이라 **여기서 안 잡힌다.**
 * 2026-09-12 에 사용자가 실제로 겪은 것이 그 경로다. 잡으려면 **「이 기기는 전에 들어온 적이
 * 있다」를 기기에 남겨야** 하는데, ① 새 클라이언트 상태가 하나 생기고 ② **가족 태블릿에서
 * 처음 오는 동생이 형의 기록 때문에 이 줄을 본다.** **PM 판단으로 넘겼다.**
 */

/** 주소에 붙이는 표식. **값은 안 본다 — 있으면 끊긴 것이다.** */
export const 끊김표식 = "kicked";

/** 인증 화면으로 보낼 주소. **부르는 쪽이 「확실히 들어와 있었다」를 아는 자리에서만 쓴다.** */
export const 끊겨서보낼곳 = `/child/auth?${끊김표식}=1`;

/**
 * **정적 빌드라 `useSearchParams` 를 쓰지 않는다.** `output: "export"` 에서 그 훅은
 * `Suspense` 경계를 요구해 **이 한 줄 때문에 화면 구조가 바뀐다.**
 * 여기는 **효과 안에서 한 번 읽는 값**이라 `location` 으로 충분하고,
 * **렌더 중에 안 읽으므로 하이드레이션도 안 어긋난다.**
 */
export function 끊겨서왔나(): boolean {
  if (typeof location === "undefined") return false;
  return new URLSearchParams(location.search).has(끊김표식);
}
