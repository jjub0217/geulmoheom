import { describe, expect, it } from "vitest";
import { detectPii } from "./pii";

/**
 * **오탐 0 이 이 파일의 합격선이다.**
 *
 * 미탐(위험한 것을 놓침)은 서버 2차(NER)가 받는다 (`공통규약.md` 「클라이언트 PII 패턴」).
 * 오탐(멀쩡한 문장을 막음)은 **아무도 못 받는다** — 아이는 자기가 뭘 잘못했는지 모른 채
 * 입력창 앞에서 막힌다. 되묻기보다 센 좌절이다.
 *
 * 통과해야 하는 문장은 `docs/안전_어휘_기준.md` 2장 화이트리스트에서 가져온다.
 */
describe("detectPii — 막으면 안 되는 문장 (오탐 0)", () => {
  it.each([
    // 안전_어휘_기준 2장 — 전투·마법·장소
    "은빛 검을 휘두르며 그림자를 베었다",
    "동굴 안으로 살금살금 들어갔다",
    "구름 위로 뛰어올라 번개를 피했다",
    "숲길을 따라 걷다가 함정을 알아챘다",
    // 숫자가 든 판타지 문장 — 전화번호로 오인하기 쉬운 자리
    "3-4번 문을 차례로 열었다",
    "100-200마리 박쥐가 쏟아져 나왔다",
    "1000년 전에 봉인된 마법이 풀렸다",
    "5000마리 늑대가 울부짖었다",
    // 학교 — 「우리 학교는 마법학교야」가 제일 큰 구멍이다
    "우리 학교는 마법학교야",
    "학교 가는 길에 나침반을 주웠다",
    // 아이가 지어낸 지명. 실제 주소와 정규식으로 못 가른다 — 서버 몫이다
    "은하시 별빛동에서 온 마법사를 만났다",
    "우리 마을 사람들을 지켰다",
    // 「초」로 끝나는 보통명사
    "약초를 달여 친구를 치료했다",
    "기초 주문을 외우고 지팡이를 들었다",
  ])("통과: %s", (text) => {
    expect(detectPii(text)).toEqual([]);
  });
});

describe("detectPii — 잡아야 하는 것", () => {
  it.each([
    ["010-1234-5678 로 전화해", "phone"],
    ["01012345678 이야", "phone"],
    ["010 1234 5678", "phone"],
    ["02-123-4567 로 걸어", "phone"],
    ["minjun@example.com 으로 보내줘", "email"],
    ["우리집은 101동 302호야", "address"],
    ["행복로 123번지에 살아", "address"],
    ["서울시 방배동 12 에 살아", "address"],
    ["나는 한빛초등학교 5학년이야", "school"],
    ["우리 학교는 한빛중학교야", "school"],
  ])("잡는다: %s → %s", (text, kind) => {
    expect(detectPii(text)).toContain(kind);
  });

  it("여러 종류가 같이 있으면 종류마다 한 번씩만 돌려준다", () => {
    const kinds = detectPii("010-1234-5678 이고 minjun@example.com 이고 010-1111-2222");
    expect(kinds).toEqual(["phone", "email"]);
  });

  it("빈 문자열은 아무것도 안 잡는다", () => {
    expect(detectPii("")).toEqual([]);
  });
});
