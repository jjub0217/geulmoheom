/**
 * **식은 서버를 깨운다** (`주차계획/W6.md` **15번** · 잠금 조건 ①).
 *
 * ## 무엇이 났나
 *
 * **무료 티어는 마지막 활동 +15분 00초에 내려간다** (2026-09-16 백엔드 실측, 세 번 대조).
 * **다시 깨는 데 32초**가 든다 — **컨테이너 14초 · `alembic`+카드 5초 · 앱 읽기 11초 ·
 * 처리 0.2초.** **그날 첫 아이가 그 32초를 맨눈으로 기다린다.**
 *
 * **⛔ 종전에 여기 적어 둔 「502 를 두 번 밟았다 · 「느리다」가 아니라 「죽는다」」는
 * 원인 오진이었다** (`주차계획/W6.md` 15번, 2026-09-16 정정). **콜드는 502 를 안 낸다** — 아래.
 * **완료 조건도 「502 를 막는다」에서 「32초를 가린다」로 바뀌었다.**
 *
 * ## 왜 이것으로 되나
 *
 * **사람은 그동안 뭔가 하고 있다.** 부모는 가입 폼에 1분 이상, 아이는 코드 입력·카드
 * 읽기·문장 쓰기에 수십 초를 쓴다. **서버가 깨는 시간이 그 시간에 겹친다.**
 *
 * **⛔ 얼마나 겹치는지는 수로 갈린다** (백엔드 실측 **두 번** — 1분 48초 잔 뒤 `GET`
 * **200 · 33.3초**, 14시간 31분 잔 뒤 `POST` **401 · 32.3초**.
 * **잠의 깊이도 메서드도 차이를 안 만들었다**):
 * - **부모 가입 폼(1분 이상)** — **이긴다.** 32초 안에 서버가 선다
 * - **아이 접속 코드 입력(십수 초)** — **진다.** 15초 만에 코드를 치면 **서버가 아직 없다**
 *
 * **⭐ 콜드를 맞는 자리는 접속 코드 하나다.** 아이 흐름의 요청 순서가
 * **`child/auth` → `child/me` → `cards/next` → `attempts`** 라(운영 로그),
 * **첫 요청이 총알을 다 맞고 뒤는 따뜻하다** — 보내기는 콜드가 아니라 **2.9초**가 기본값이다.
 * **그 한 자리에서 이기느냐 지느냐가 전부**다.
 *
 * **그래서 이 장치는 32초를 0 으로 만들지 못한다** — 없는 것보다 확실히 낫다는 것까지다.
 * **지는 쪽에서는 화면이 기다림을 말해 주는 것이 남는 일**이고, 그래서 자녀 인증 화면이
 * 보내는 동안 `문구.md` 2.5 를 쓴다.
 *
 * **⛔ 「502 가 정상 경로다」는 틀렸다 — 콜드는 502 를 안 낸다** (2026-09-16).
 * **콜드 넷이 다 정상 응답**이었고 **받은 로그 전체에 502 가 한 번도 안 찍혔다.**
 * **당연하다 — 502 는 앱에 안 닿은 요청**인데 **콜드에서는 앞단이 32초를 기다려 주니 닿는다.**
 *
 * **안 닿는 창은 따로 있다 — 배포 전환**이다(헌 인스턴스가 내려가고 새 것이 아직 안 뜬
 * 몇 초 · 백엔드 가설, 확정 아님). **⭐ 그리고 이 장치는 그것을 원리적으로 못 막는다 —
 * 깨우기는 잠든 것을 깨우지 배포를 막지 못한다.**
 * **그래서 「502 를 막았다」는 여기 어디에도 안 쓴다.** 이 장치가 하는 일은 **32초를 가리는 것**이다.
 *
 * ## ⛔ 지키는 것 넷
 *
 * - **응답을 안 본다.** 깨우기는 **결과를 쓰지 않는다** — 200 이든 401 이든 502 든
 *   하는 일이 같다. 실패해도 화면을 안 건드리고 **아이·부모에게 오류를 보이지 않는다**
 * - **⛔ 자동 재시도가 아니다.** 502 는 **요청이 앱에 닿았는지 밖에서 못 가른다** —
 *   `POST /parents/children` 을 다시 치면 **자녀가 둘 생긴다.**
 *   **깨우는 것과 다시 보내는 것은 다른 일이다**
 * - **화면이 열려 있는 동안만** 친다. 「주기적으로 깨워 두기」와 다르다 — 그건 **아무도
 *   안 써도 24시간** 깨워 무료 사용 시간(750h)을 다 쓴다
 * - **탭이 숨으면 멈춘다.** 안 그러면 **열어 두고 잊은 탭이 계속 친다**
 *
 * ## ⚠ 막는 것과 못 막는 것 — 좁혀서 적는다
 *
 * **막는다** — **보면서 오래 쓰는 아이.** 문장을 **15분** 넘게 써도(**마지막 활동 +15분 00초**에
 * 내려간다) **10분마다 치므로 세션 중간에 잠들지 않는다.** ②가 막으려던 것이 이 자리다.
 * **⛔ 종전 「16분 41초」는 계산 착오였다** — 기준점으로 잡은 `/healthz` 뒤에
 * **배포의 Render 자체 프로브**가 한 번 더 들어왔고 **그것이 마지막 활동**이었다.
 * **세 번 대조해 전부 15분 00초**다 (2026-09-16 정정). **`깨우는간격` 의 근거가 이 수다.**
 *
 * **⛔ 못 막는다** — **탭을 벗어났다 돌아와 곧바로 보내는 아이.** 숨은 동안 타이머가
 * 멈추므로(요금 조건이다) **20분 뒤 돌아오면 서버는 자고 있고**, 복귀 핑과 제출이
 * **거의 같이 나가** 32초를 못 번다. **설계상 값을 치른 구멍이지 결함이 아니다** —
 * **얼마나 흔한지는 관찰로 본다.**
 */

/** 10분. **15분에 내려가므로** 그보다 짧아야 하고, 짧을수록 헛되이 친다. */
export const 깨우는간격 = 10 * 60 * 1000;

/**
 * 깨우기를 시작한다. **되돌려 주는 함수를 부르면 멈춘다.**
 *
 * **브라우저 것을 안 만진다** — `document` 를 여기서 부르지 않고 **보임 여부와 구독을
 * 받아 쓴다.** 그래야 **시계를 돌려 가며 검사**할 수 있다.
 *
 * **보이는 동안만 돈다** — 숨으면 멈추고, **다시 보이면 그 자리에서 한 번 친다.**
 * 돌아온 순간이 **다음 요청 직전**이라, 거기서 안 치면 **이 장치가 막으려던 502 를
 * 그대로 만난다.**
 */
export function 깨우기시작(
  친다: () => void,
  {
    보이나,
    구독,
    간격 = 깨우는간격,
  }: {
    /** 지금 탭이 보이나. */
    보이나: () => boolean;
    /** 보임이 바뀔 때 부를 곳. **끊는 함수를 돌려준다.** */
    구독: (바뀜: (보이나: boolean) => void) => () => void;
    간격?: number;
  },
): () => void {
  let 타이머: ReturnType<typeof setInterval> | null = null;

  const 돌린다 = () => {
    if (타이머 === null) 타이머 = setInterval(() => 친다(), 간격);
  };
  const 멈춘다 = () => {
    if (타이머 !== null) {
      clearInterval(타이머);
      타이머 = null;
    }
  };
  /** **화면이 뜨는 그 순간이 가장 중요한 한 번**이다 — 사람이 첫 요청을 보내기까지 수십 초가
   * 남아 있고, **서버가 깨는 시간이 정확히 그만큼**이다. */
  const 지금친다 = () => {
    친다();
    돌린다();
  };

  if (보이나()) 지금친다();
  const 끊는다 = 구독((보임) => (보임 ? 지금친다() : 멈춘다()));

  return () => {
    끊는다();
    멈춘다();
  };
}
