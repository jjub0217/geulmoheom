import type { components } from "@/api/types.gen";

type ArtworkRef = components["schemas"]["ArtworkRef"];

/**
 * 챕터가 도는 동안 **액자에 무엇을 둘지** 고른다 (`주차계획/W7.md` **8번** · `api/Stage1.md`).
 *
 * ## ⛔ 왜 필요한가 — 계약이 화면 규칙을 박아 뒀다
 *
 * **핵심 씬이 1턴·9턴 둘뿐이다.** 나머지 여덟 턴에는 **새 그림이 없고 `artwork` 가 `null`**
 * 로 온다(`db327d6` 명세 변경). **그때 액자를 비우면 아이 눈에 「그림이 사라지는 것」이 된다.**
 *
 * **⭐ 그림은 보상 그 자체다** — `adr/0015` 가 하루를 통째로 쓴 이유가 그것이다.
 * **여덟 턴 중 일곱에서 보상이 사라지는 화면**을 만들지 않는다.
 *
 * ## 그래서 규칙은 하나다 — **`null` 은 「없다」가 아니라 「그대로」다**
 *
 * **`null` 을 「지워라」로 읽지 않는다.** 새 그림이 올 때만 갈아 끼우고, 안 오면 **직전
 * 핵심 씬 그림을 그대로 둔다.**
 *
 * ## ⛔ 왜 컴포넌트 안의 `useState` 로 안 두나
 *
 * **여기가 틀리면 아이가 남의 장면 그림을 본다** — 챕터가 바뀌었는데 앞 그림이 남는 자리다.
 * 훅 안에 두면 **그 자리를 재려고 화면을 띄워야** 하고, 그러면 **뒤집기가 무거워서 안 하게 된다.**
 * **순수 함수면 검사가 한 줄이다.**
 */
export function 액자에둘것(
  직전: ArtworkRef | null,
  이번: ArtworkRef | null | undefined,
): ArtworkRef | null {
  // **새로 왔으면 갈아 끼운다.** 그 밖에는 직전 것을 그대로 둔다.
  return 이번 ?? 직전;
}

/**
 * 챕터가 바뀌면 **직전 그림을 버린다.**
 *
 * **⛔ 이것이 없으면 앞 챕터 그림이 새 챕터 1턴에 남는다** — 1턴은 핵심 씬이라 곧 새 그림이
 * 오지만, **그 사이 몇 초 동안 아이는 지난 이야기의 그림을 본다.** 「내가 쓴 거랑 그림이
 * 다른데?」는 **아이 셋이 실제로 한 말**이다(`adr/0015`).
 *
 * **⚠ 같은 챕터를 이어하는 경우와 갈라야 한다** — 새로고침으로 돌아온 아이는 `chapter_id`
 * 가 같고, 그때는 **버리면 안 된다.**
 */
export function 챕터가바뀌었나(직전챕터: string | null, 이번챕터: string): boolean {
  return 직전챕터 !== null && 직전챕터 !== 이번챕터;
}
