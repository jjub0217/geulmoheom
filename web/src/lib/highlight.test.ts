import { describe, expect, it } from "vitest";

import { PII_MASK } from "./pii";
import { 하이라이트조각 } from "./highlight";

/** 강조된 도막만 뽑는다. */
const 강조된 = (조각들: { text: string; 강조: boolean }[]) =>
  조각들.filter((c) => c.강조).map((c) => c.text);
/** 도막을 다시 이으면 원문이어야 한다. */
const 이어붙임 = (조각들: { text: string }[]) =>
  조각들.map((c) => c.text).join("");

describe("묘사어 하이라이트", () => {
  it("문장을 한 글자도 잃지 않는다", () => {
    // **가장 먼저 지킬 것**이다. 아이 문장은 창작물이라 표시하려다 깎으면 안 된다.
    const 문장 = "은빛 물고기가 살금살금 지나갔다";
    const 조각들 = 하이라이트조각(문장, [
      { text: "은빛", kind: "adj" },
      { text: "살금살금", kind: "adv" },
    ]);
    expect(이어붙임(조각들)).toBe(문장);
    expect(강조된(조각들)).toEqual(["은빛", "살금살금"]);
  });

  it("못 찾으면 조용히 건너뛴다 — 화면이 죽지 않는다", () => {
    // 서버가 「원문에 그대로 있는 것만」 보내기로 돼 있지만(4절) **그 위에 선다.**
    // 활용형이 원형으로 오면(「캄캄했지만」 → 「캄캄한」) 여기로 떨어진다.
    const 문장 = "캄캄했지만 앞으로 나아갔다";
    const 조각들 = 하이라이트조각(문장, [{ text: "캄캄한", kind: "adj" }]);
    expect(이어붙임(조각들)).toBe(문장);
    expect(강조된(조각들)).toEqual([]);
  });

  it("하이라이트가 없어도 문장은 그대로 나온다", () => {
    const 조각들 = 하이라이트조각("문을 연다", []);
    expect(이어붙임(조각들)).toBe("문을 연다");
    expect(강조된(조각들)).toEqual([]);
  });

  it("긴 것이 이긴다 — 짧은 쪽이 먼저 자리를 차지하면 긴 말이 통째로 떨어진다", () => {
    const 조각들 = 하이라이트조각("살금살금 걸었다", [
      { text: "살금", kind: "adv" },
      { text: "살금살금", kind: "adv" },
    ]);
    expect(강조된(조각들)).toEqual(["살금살금"]);
  });

  it("같은 말을 두 번 썼으면 두 번 다 표시한다", () => {
    // 한 번만 표시되면 아이 눈에는 **왜 저기는 안 되나**로 보인다.
    const 조각들 = 하이라이트조각("낡은 문과 낡은 계단", [
      { text: "낡은", kind: "adj" },
    ]);
    expect(강조된(조각들)).toEqual(["낡은", "낡은"]);
  });

  it("가려진 자리를 강조 대상으로 삼지 않는다", () => {
    // 서버는 **최종 마스킹본**에서 하이라이트를 만든다(PM 확인 2026-09-08). 그래서
    // 가려진 낱말은 애초에 안 내려온다 — **틀리는 방향이 안전한 쪽**이다.
    // 여기서 막는 것은 그 뒤의 자리: **어쩌다 `○○○` 가 섞여 와도 문장을 안 건드린다.**
    const 문장 = `등대지기한테 ${PII_MASK} 로 전화한다`;
    const 조각들 = 하이라이트조각(문장, [{ text: "전화한다", kind: "clause" }]);
    expect(이어붙임(조각들)).toBe(문장);
    expect(강조된(조각들)).toEqual(["전화한다"]);
  });
});
