import type { 삽화상태 } from "@/lib/artwork";

/**
 * 「모험 그림」 자리가 **무엇을 말해야 하나** (2026-09-22 사용자 확정).
 *
 * ## ⛔ 왜 있나 — 아이가 오해할 자리였다
 *
 * **본편 삽화는 매 턴 만들어지지 않는다.** 한 챕터에 **두 번**뿐이다(`챕터뼈대_초안.md`
 * 「핵심 씬」 — 1턴과 9턴). 나머지 턴에는 새 그림이 없고, 화면은 **직전 그림을 그대로
 * 둔다**(`chapter-artwork.ts` — 비우면 아이 눈에 그림이 사라진다).
 *
 * 그런데 그 그림이 **아이 문장 바로 옆**에 붙어 있었다. 그러면 2턴부터도
 * **「내가 방금 쓴 글로 이 그림이 나왔다」**로 읽힌다. **사용자가 그것을 짚었다.**
 *
 * ## ⛔ 턴 번호로 가르지 않는다
 *
 * **서버가 새 그림을 만든 턴에만 `artwork` 를 싣는다.** 화면은 그 id 가 지금 액자에
 * 있는 것과 같은지만 본다 — **그것이 「이번 글로 나온 그림인가」의 실제 신호**다.
 * 턴 번호를 세면 **뼈대가 바뀌는 순간 화면이 거짓말을 한다.**
 *
 * ## ⛔ 기본 삽화는 아무 말도 하지 않는다
 *
 * 생성 실패·검사 차단·60초 초과가 **전부 `ready` + `fallback` 으로 수렴한다**
 * (`artworks.py`). 그때 **「새 그림이 완성됐어!」는 거짓**이고, **「기본 그림이야」는
 * 「`fallback` 을 아이에게 알리지 않는다」**(대표 판정 · 미결 11-5·11-7)를 깬다.
 *
 * **그래서 아무 말도 안 한다.** 사용자 확정이다 — 거짓말도 아니고 알리는 것도 아니다.
 */
export type 그림말 = "새로왔다" | "앞에서만든것" | "만드는중" | "말없음";

export function 그림이할말(
  상태: 삽화상태,
  이번글로왔나: boolean,
): 그림말 {
  // 자리를 통째로 빼는 상태다. 말할 그림이 없다.
  if (상태.kind === "못받음") return "말없음";

  // **⛔ 만드는 중에도 「이번 글로 만드는 것」일 때만 말한다.**
  // 앞 턴 그림을 다시 확인하는 중일 수도 있고, 그때 「중요한 순간」이라고 하면
  // **아이가 안 쓴 것을 자기가 한 일로 읽는다.**
  if (상태.kind === "기다림") return 이번글로왔나 ? "만드는중" : "말없음";

  // **기본 에셋이면 말없음이 먼저다.** 이번 글로 온 것이어도 그렇다 —
  // 그 그림은 **아이 문장으로 만든 것이 아니다.**
  if (상태.fallback === true) return "말없음";

  return 이번글로왔나 ? "새로왔다" : "앞에서만든것";
}
