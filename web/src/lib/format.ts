/**
 * 값의 형식 (`docs/문구.md` **6장**). **SSOT 는 문서이고 여기는 그 규칙을 구현한 것**이다.
 *
 * 원칙 하나 — **기계가 준 값을 그대로 화면에 내지 않는다.**
 * ISO 시각 · UUID · enum(`PII_DETECTED`) · 불리언(`true`) 전부 해당한다.
 * **`용어사전.md` 9장의 「읽어도 모르면 고지가 아니라 알리바이다」는 문장에만 걸리는 규칙이 아니다.**
 *
 * **이 파일이 생긴 이유**: 학부모 화면에 **「동의하신 날짜와 시간: 2026-09-08T01:00:00Z」**가
 * 그대로 나갔다. **문장은 3.6 에 등록돼 있었는데 값의 형식이 어디에도 없었다** —
 * **문구 누락과 같은 자리인데 아무도 문구라고 생각하지 않는 자리**다.
 */

/**
 * 학부모 화면의 날짜·시각 (`문구.md` 6장) — **YYYY년 M월 D일 오전/오후 H시 M분**.
 *
 * 지키는 것 셋 —
 * ① **기기 로컬 시간이다.** 서버는 UTC(`Z`)로 준다. `Date` 의 getter 들이 로컬로 바꿔 주므로
 *    **`getUTC*` 를 쓰면 안 된다** — 그대로 쓰면 **아홉 시간 어긋난 시각을 학부모가 본다.**
 * ② **초를 안 보여준다.** 정확한 값은 DB 가 들고 있고 **화면은 사람이 확인하는 자리**다.
 * ③ **24시간제를 안 쓴다.** 「오전/오후 + 12시간」이 한국어 화면의 기본이고
 *    「13시」는 서식 문서의 말이다.
 *
 * **`Intl.DateTimeFormat("ko-KR")` 을 안 쓴다** — `dateStyle`·`timeStyle` 이 내는 것은
 * 「2026. 9. 8. 오전 10:34」라 **6장이 정한 모양이 아니다.** 형식이 문서에 박혀 있으므로
 * 여기서 그 모양을 만든다.
 *
 * **못 읽으면 `null` 이다.** 서버가 이상한 값을 줘도 **「NaN년 NaN월」을 내보내지 않는다** —
 * 기계 말이 새는 것을 막자고 만든 함수가 더 나쁜 기계 말을 내면 안 된다.
 * 부르는 쪽은 `null` 이면 **그 줄을 통째로 안 그린다.**
 */
export function 날짜시각(iso: string): string | null {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return null;

  const 시각 = d.getHours();
  // 0시는 「오전 12시」, 12시는 「오후 12시」다. `% 12` 만 쓰면 둘 다 「0시」가 된다.
  const 열두시간 = 시각 % 12 === 0 ? 12 : 시각 % 12;

  return (
    `${d.getFullYear()}년 ${d.getMonth() + 1}월 ${d.getDate()}일 ` +
    `${시각 < 12 ? "오전" : "오후"} ${열두시간}시 ${d.getMinutes()}분`
  );
}
