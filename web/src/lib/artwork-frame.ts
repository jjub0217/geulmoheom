import type { CSSProperties } from "react";

/**
 * 삽화 액자의 비율과 자리 (`docs/api/Stage0.md` **5절 「화면 비율」**).
 *
 * **여기가 이 값을 정하는 자리가 아니다.** 계약 문서가 SSOT 이고 여기는 옮겨 온 것이다 —
 * **비율이 바뀌면 계약이 먼저 바뀌고 화면이 따라온다.** 그래서 화면 파일마다 흩어 두지 않고
 * 이 한 자리에 둔다 (2026-09-08 PM 판정).
 *
 * **왜 생겼나** — 결과 연출(A0-3)과 내 책(A0-4)이 둘 다 액자를 **`aspect-4/3` 가로 상자**에
 * `object-cover` 로 두고 있었다. 그런데 **오는 그림은 세로 0.58** 이라, 폭을 채우면 그림이
 * 상자보다 훨씬 길어져 **세로로 43%만 보이고 위아래 각 28%가 잘렸다.**
 * **레이아웃이 튀는 문제가 아니라 아이 그림의 절반 넘게가 이미 안 보이고 있었다.**
 */

/**
 * 가로:세로. **실측값을 그대로 적는다** — `0.58` 이라는 반올림된 수보다
 * **어디서 나온 값인지가 남아야** 바뀔 때 대조할 수 있다 (`Stage0.md` 5절, 20/20 장 `784×1353`).
 *
 * **이 값을 정하고 있는 것은 화면 설계가 아니다** — 가이드 레퍼런스 크롭(`819×1413`)이
 * 0.58 이고 모델이 그 비율을 따라간 것이다. 즉 `app/artwork.py` 의 사각형이 정한다.
 */
export const 삽화비율 = 784 / 1353;

/**
 * **결과 화면 액자의 높이 상한.**
 *
 * **없으면 그림 하나가 화면을 다 먹는다** — 모바일 세로(390×844)에서 폭을 다 쓰면
 * 액자가 **672px** 라, 바로 아래 등급 배지·가이드·아이 문장·「내 책」이 통째로 접힌다.
 *
 * **`svh` 다.** 주소창이 보이는 상태의 높이라 **접힐 수 있는 브라우저 크롬을 계산에 넣지 않는다** —
 * `vh` 로 두면 크롬이 보이는 첫 화면에서 넘친다.
 *
 * **⛔ 60 에서 50 으로 내렸다** (2026-09-15, 아동 3명 관찰 ③ · 잠금 조건 ①).
 * **60 은 「액자가 화면을 다 먹지 않는다」만 봤고 「그 아래가 다 들어가는가」는 안 봤다** —
 * 실측하니 **세 뷰포트 전부에서 「내 책」이 첫 화면 밖**이었다(996 / 1015 / 977).
 * **가로는 2열로 갈라 풀리지만**(`page.tsx`) **세로는 한 열이라 이 값이 유일한 여유**다.
 *
 * **⭐ 상한을 두 방향에서 잰다.** 위로는 「화면을 다 먹지 않는다」, 아래로는
 * **「액자가 첫 화면 높이의 30% 는 된다」** — 아래 난간이 없으면 **넘침을 줄이려고 그림을
 * 접는 것**이 언제든 답이 된다. 그림이 보상인데 그것을 깎으면 **고친 게 아니다.**
 */
export const 결과액자최대높이 = "50svh";

/**
 * 액자 자리. **폭이 아니라 높이로 잘라낸다.**
 *
 * 높이 상한을 `max-height` 로 걸면 **상자가 비율을 잃고 옆으로 퍼져** 그림이 레터박스로 앉는다.
 * 대신 **높이 상한을 폭 상한으로 환산해서** 걸면, 화면이 낮을 때 **상자가 통째로 작아지고
 * 비율은 그대로**다 — 자르지도 않고 여백도 안 생긴다.
 *
 * @param 최대높이 CSS 길이. 안 주면 상한 없이 폭을 다 쓴다 (내 책은 세로로 넘기는 목록이다).
 */
export function 액자자리(최대높이?: string): CSSProperties {
  return {
    aspectRatio: String(삽화비율),
    ...(최대높이 === undefined
      ? {}
      : { maxWidth: `calc(${최대높이} * ${삽화비율})` }),
  };
}
