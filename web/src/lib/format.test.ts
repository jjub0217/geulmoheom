import { describe, expect, it } from "vitest";

import { 날짜시각 } from "./format";

/**
 * `docs/문구.md` 6장. **형식이 문서에 박혀 있어 여기서 글자까지 본다.**
 *
 * **로컬 시간을 재려면 기준 시간대가 있어야 한다.** `vitest.config.ts` 가 아니라
 * 여기서 만드는 값으로 고정한다 — **오프셋을 직접 만들어 넣으면 어느 기계에서도 같은 답이 나온다.**
 */

/** 로컬 자정 기준으로 오프셋을 붙여 만든다 — 실행 기계의 시간대와 무관하게 같은 결과다. */
function 로컬(y: number, m: number, d: number, h: number, min: number): string {
  return new Date(y, m - 1, d, h, min).toISOString();
}

describe("날짜시각 — 학부모 화면", () => {
  it("YYYY년 M월 D일 오전/오후 H시 M분 이다", () => {
    expect(날짜시각(로컬(2026, 9, 8, 10, 34))).toBe("2026년 9월 8일 오전 10시 34분");
  });

  it("오후는 12시간제로 바꾼다 — 「13시」는 서식 문서의 말이다", () => {
    expect(날짜시각(로컬(2026, 9, 8, 13, 5))).toBe("2026년 9월 8일 오후 1시 5분");
  });

  it("정오와 자정을 0시로 만들지 않는다", () => {
    // `% 12` 만 쓰면 둘 다 「0시」가 된다.
    expect(날짜시각(로컬(2026, 9, 8, 12, 0))).toBe("2026년 9월 8일 오후 12시 0분");
    expect(날짜시각(로컬(2026, 9, 8, 0, 0))).toBe("2026년 9월 8일 오전 12시 0분");
  });

  it("초를 보여주지 않는다 — 화면은 사람이 확인하는 자리다", () => {
    const 초가있는값 = new Date(2026, 8, 8, 10, 34, 59).toISOString();
    expect(날짜시각(초가있는값)).toBe("2026년 9월 8일 오전 10시 34분");
  });

  it("UTC 를 그대로 내지 않는다 — 기기 로컬 시간이다", () => {
    // 서버는 `Z` 로 준다. **그대로 쓰면 아홉 시간 어긋난 시각을 학부모가 본다.**
    const 나온것 = 날짜시각("2026-09-08T01:00:00Z");
    expect(나온것).not.toBeNull();
    // 같은 순간을 로컬로 읽은 것과 같아야 한다 — 어느 시간대에서 돌려도 참이다.
    const 같은순간 = new Date("2026-09-08T01:00:00Z");
    expect(나온것).toContain(`${같은순간.getDate()}일`);
    expect(나온것).toContain(`${같은순간.getMinutes()}분`);
  });

  it("못 읽는 값이면 null 이다 — 「NaN년」을 내보내지 않는다", () => {
    // 기계 말이 새는 걸 막자고 만든 함수가 **더 나쁜 기계 말**을 내면 안 된다.
    expect(날짜시각("어제")).toBeNull();
    expect(날짜시각("")).toBeNull();
  });

  it("ISO 원문이 결과에 남지 않는다", () => {
    const 나온것 = 날짜시각("2026-09-08T01:00:00Z") ?? "";
    for (const 기계말 of ["T", "Z", "-", ":"]) {
      expect(나온것).not.toContain(기계말);
    }
  });
});
