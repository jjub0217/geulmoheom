/**
 * **별명 뒤에 붙는 목적격 조사.** `문구.md` 3.9 는 「⟨별명⟩**을** 지울까요?」로 적혀 있는데
 * **별명은 학부모가 자유롭게 짓는 값**이라 받침이 없으면 「나비을」이 된다.
 *
 * **문구를 바꾸는 것이 아니라 값의 모양을 정하는 것이다** — `문구.md` **6장**이
 * 「기계가 준 값을 그대로 화면에 내지 않는다」로 세운 그 자리이고, ISO 시각이 샜던 것과 같은
 * 종류다: **문장은 등록돼 있었는데 값이 문장에 들어가는 모양이 어디에도 없었다.**
 * **PM 에게 3.9 등록을 요청해 뒀다.**
 *
 * 한글이 아니면 3.9 가 적은 「을」을 그대로 쓴다 — **지어내지 않는다.**
 */
function 을를(별명: string): string {
  const 끝 = 별명.trim().at(-1) ?? "";
  const 코드 = 끝.charCodeAt(0);
  if (Number.isNaN(코드) || 코드 < 0xac00 || 코드 > 0xd7a3) return "을";
  return (코드 - 0xac00) % 28 === 0 ? "를" : "을";
}

