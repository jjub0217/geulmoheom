const 걸린것: Record<string, string> = {
  name: "이름",
  school: "학교 이름",
  phone: "전화번호",
  email: "메일 주소",
  address: "사는 곳",
};

export function 별명이걸렸다(kind: unknown): string | null {
  const 무엇 = typeof kind === "string" ? 걸린것[kind] : undefined;
  // **모르는 `kind` 면 지어내지 않는다.** 서버가 종류를 늘렸는데 여기가 안 따라온 경우다 —
  // 빈칸으로 문장을 만들면 「별명에 이(가) 들어 있어요」가 된다.
  if (무엇 === undefined) return null;
  return `별명에 ${무엇}이(가) 들어 있어요. 다른 별명으로 지어주세요.`;
}

