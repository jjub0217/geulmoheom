import { describe, expect, it } from "vitest";

import { 턴문구 } from "@/components/turn-copy";

/**
 * **문구가 `docs/문구.md` 1.18 을 벗어났는지는 `make check-copy` 가 본다.**
 * 여기서 재는 것은 **그 장치가 못 보는 것** — 1.18 이 산문으로 적어 둔 **금지**다.
 * 「이 문장이 문서에 있다」와 「이 문장이 규칙을 지킨다」는 다르다.
 */
describe("턴문구 — 1.18 의 급소", () => {
  it("직접 쓰기 유도는 「아니면」으로 시작한다", () => {
    // 「아니면」은 **둘이 같은 무게**라고 말한다. 빼면 「직접 쓰기」가
    // **나중에 붙은 것**으로 읽힌다 — 1.18 이 급소로 지목한 자리다.
    expect(턴문구.직접쓰기유도.startsWith("아니면")).toBe(true);
  });

  it("고르는 것을 나무라는 말이 없다", () => {
    // **선택지는 막힌 아이의 길**이다. 부추기는 일은 계약(선택지 턴도 등급)이 한다.
    for (const 금지 of ["재미없", "더 좋아", "그것보다", "겨우"]) {
      expect(턴문구.직접쓰기유도).not.toContain(금지);
      expect(턴문구.입력안내).not.toContain(금지);
    }
  });

  it("재촉하지 않는다 — 「써봐」가 아니다", () => {
    // 「직접 써봐!」는 **재촉**으로 읽힌다 (1.18).
    expect(턴문구.직접쓰기유도).not.toContain("써봐");
  });

  it("입력 안내는 「자세히」를 쓰고 「길게」를 안 쓴다", () => {
    // **구체적으로 쓰는 것**을 부탁한다. 「길게」는 1.12 금지 목록이다.
    expect(턴문구.입력안내).toContain("자세히");
    expect(턴문구.입력안내).not.toContain("길게");
  });

  it("아이 화면 금지어가 없다", () => {
    // `용어사전.md` 8장. 변수·주석은 자유지만 **화면에 나가는 문자열**은 아니다.
    for (const 문장 of Object.values(턴문구)) {
      for (const 금지 of ["점수", "연습", "학습", "채점", "보스", "앨범", "등급"]) {
        expect(문장).not.toContain(금지);
      }
    }
  });
});
