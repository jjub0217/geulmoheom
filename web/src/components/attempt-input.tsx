/**
 * **쓰는 자리 하나가 한 덩어리다** (2026-09-09, 실기기에서 사용자가 보고 고침).
 *
 * 전에는 **라벨·나침반·입력창·「보내기」가 각각 떨어져** 있었다. 그래서 셋이 안 읽혔다 —
 * ① 라벨 옆 나침반이 **무엇에 반응하는 물건인지** 안 보였고 ② 「보내기」가 **오른쪽 아래 멀리**
 * 있어 쓰던 자리와 끊겼고 ③ 칸이 낮아 **짧게 쓰라는 신호**를 줬다.
 *
 * **만 11세는 라벨이 아니라 「가까움」과 「담김」으로 관계를 읽는다.** 그래서 넷을 **테두리 하나 안**에
 * 넣었다 — 물음이 위, 쓰는 칸이 가운데, **나침반과 「보내기」가 같은 바닥 줄**이다.
 * **나침반이 자기 글자 옆에서 밝아지므로** 무엇이 무엇을 움직이는지가 자리로 보인다.
 *
 * **숫자·바·퍼센트는 여전히 없다** (PRD A0-2 MUST). **읽히게 만드는 것과 숫자를 쓰는 것은 다르다** —
 * 바꾼 것은 나침반의 **자리**이지 표시 방식이 아니다.
 */
export function AttemptInput({
  label,
  value,
  onChange,
  onMasked,
  onSend,
  보낼수있나,
  보내기라벨,
  보내는중 = false,
  안내글,
  disabled = false,
  showCompass = true,
  제목보임 = false,
  이어쓰기신호,
}: {
  label: string;
  value: string;
  onChange: (value: string) => void;
  /** 가린 **종류**만 알린다. 문장은 넘기지 않는다. */
  onMasked?: (kinds: PiiKind[]) => void;
  /** 「보내기」가 이 안에 있다. **쓰던 자리와 보내는 자리를 떼어놓지 않는다.** */
  onSend: () => void;
  보낼수있나: boolean;
  /** `문구.md` 2.2. **여기서 짓지 않는다** — 부모가 상수를 넘긴다. */
  보내기라벨: string;
  /**
   * **보내는 중인가** (2026-09-23 사용자 지시 — 진행 상태를 두 곳에서 말하지 않는다).
   *
   * **⛔ 버튼 글자를 바꾸지 않는다.** 종전에는 부르는 쪽이 `보내기라벨` 자체를
   * **「그림을 준비하는 중…」·「이야기를 잇는 중…」**으로 갈아 끼웠는데, **같은 순간
   * 다른 자리가 이미 진행 상태를 말하고 있었다**(`StoryReading`). 한 화면이 같은 일을
   * 두 번 설명했고, **카드 화면에서는 둘이 서로 다른 단계**를 말했다.
   *
   * **⛔ 프론트는 서버가 지금 어느 단계인지 모른다.** `POST /attempts`·`POST /turns` 는
   * **요청 하나**다 — 읽는 중·평가 중·이야기 만드는 중·그림 굽는 중을 **가를 방법이 없다.**
   * 그래서 **버튼은 원래 행동 글자를 그대로** 두고 **돌아가는 표시와 잠금**만 더한다.
   */
  보내는중?: boolean;
  /**
   * 빈 칸에 뜨는 안내 (`문구.md` 1.18 「어떻게 할지 자세히 말해줘!」).
   *
   * **⛔ 여기서 짓지 않는다** — 부모가 상수를 넘긴다. **Stage 0 카드 화면은 안 넘긴다**:
   * 거기는 **물음(`prompt_label`)이 이미 바로 위에 있어** 안내가 같은 말을 두 번 하게 된다.
   * **없으면 안 그린다** — 빈 문자열을 넘기는 것과 같게 두면 「자리는 있는데 비었다」가 된다.
   */
  안내글?: string;
  disabled?: boolean;
  /** 게임 무대에서는 입력창이 열리기 전에 상위 대화창이 나침반을 소개한다. */
  showCompass?: boolean;
  /**
   * **쓰는 칸의 이름을 화면에도 보일까** (2026-09-24 사용자 지시).
   *
   * **⛔ 지금은 어느 화면도 참이 아니다.** `문구.md` **1.18** 이 2026-09-22 에
   * **「묻는 것은 래서판다 하나」**로 정해 다섯 글쓰기 화면 모두 이름을 감췄다.
   * **그래도 값을 두는 이유**는 아래 제목 행이 **「보이는 것이 있을 때만」** 그려지는데,
   * 그 조건이 **나침반 하나에만 걸려 있으면 뜻이 좁아지기 때문**이다.
   * 보이는 제목이 다시 필요해지는 날 **이 값을 참으로 주면 행이 제자리를 찾는다.**
   */
  제목보임?: boolean;
  /**
   * **값이 바뀌면 입력칸에 초점을 주고 커서를 글 맨 뒤에 놓는다.** 되묻기가 왔을 때 쓴다.
   *
   * **⛔ 칸을 비우지 않는 것이 설계다** — `MVP_PRD.md` **4.4** 의 되묻기 틀 넷 중 셋이
   * **보태라는 말**이다(「조금만 더 말해줄래?」·「뭐가 보이고 들리는지 알려줘」). 그런데
   * **화면이 그 말을 안 해서** 아이 눈에는 **「새 질문 + 이미 차 있는 칸」**으로 보였고,
   * **지우고 새로 쓰는 것이 자연스러운 반응**이 됐다.
   *
   * **⛔ 비우는 쪽으로 풀지 않는다.** 4.4 가 **「다시 써」를 금지어로** 박아 뒀는데
   * **칸을 비우면 그 말을 동작으로 하는 것**이다. 말로 안 하기로 한 것을 동작으로 하면 같다.
   * **커서를 끝에 두어 「여기서부터 이어 쓰면 된다」를 손끝으로 말한다.**
   */
  이어쓰기신호?: number;
}) {
  const introduction = useCompassIntroduction();
  const 입력창 = useRef<HTMLTextAreaElement>(null);
  /**
   * **한글 조합 중에는 값을 갈아치우지 않는다.** 조합 중인 글자를 바꿔치기하면
   * IME 가 조합을 잃고 글자가 깨진다 — 취향이 아니라 버그다.
   * 「우리 학교는 한빛초등학교야」처럼 **한글이 섞인 패턴에서 실제로 터진다.**
   */
  const 조합중 = useRef(false);
  /** 치환 뒤 커서를 되돌릴 자리. 값이 바뀐 **다음**에 놓아야 해서 렌더를 한 번 건너뛴다. */
  const 되돌릴커서 = useRef<number | null>(null);
  const [안내, set안내] = useState<string | null>(null);

  /**
   * **처음 뜰 때는 초점을 가져가지 않는다.** 종전에는 신호가 `0` 으로 시작하는 것도
   * 「바뀌었다」로 쳐서 **화면이 열리자마자 입력칸이 초점을 뺏었다** — 읽는 칸과 동료가
   * 가져가야 할 초점이었고, **검사 4건이 그것을 잡았다**(2026-09-21).
   * **바뀐 순간에만** 움직이도록 직전 값을 들고 비교한다.
   */
  const 지난신호 = useRef(이어쓰기신호);

  useEffect(() => {
    if (이어쓰기신호 === undefined) return;
    if (지난신호.current === 이어쓰기신호) return;
    지난신호.current = 이어쓰기신호;
    const 칸 = 입력창.current;
    if (칸 === null || disabled) return;
    // **한글 조합 중에는 손대지 않는다.** 커서를 옮기면 조합이 깨진다 — 위 `조합중` 과 같은 이유다.
    if (조합중.current) return;
    칸.focus();
    const 끝 = 칸.value.length;
    칸.setSelectionRange(끝, 끝);
  }, [이어쓰기신호, disabled]);

  // 값이 화면에 반영된 **직후** 커서를 놓는다. `useEffect` 로 하면 한 프레임 동안
  // 커서가 맨 끝에 가 있는 것이 보인다.
  useLayoutEffect(() => {
    const 자리 = 되돌릴커서.current;
    if (자리 === null || !입력창.current) return;
    되돌릴커서.current = null;
    입력창.current.setSelectionRange(자리, 자리);
  }, [value]);

  const 가리고전달 = (raw: string, caret: number) => {
    const r = maskPii(raw, caret);
    onChange(r.text);

    if (r.kinds.length === 0) {
      // **가린 자리가 남아 있는 동안은 안내를 지우지 않는다.** 다음 글자 하나에 사라지면
      // 아이가 읽기 전에 없어지고, 자기 글자가 왜 바뀌었는지 알 방법이 사라진다.
      if (!r.text.includes(PII_MASK)) set안내(null);
      return;
    }
    되돌릴커서.current = r.caret;
    set안내(r.kinds.map((k) => 가림안내[k]).join(" "));
    onMasked?.(r.kinds);
  };

  return (
    <div className="attempt-input" data-writing-started={value.length > 0}>
      {/* **테두리가 이 덩어리를 감싼다.** 전에는 테두리가 `textarea` 에만 있어
          「보내기」가 **다른 물건**으로 보였다. 초점 표시도 여기로 올라온다 —
          `focus-within` 이라 **키보드로 들어와도 어느 자리인지 보인다.** */}
      {/* **물음은 테두리 밖이다** (2026-09-09, 실기기에서 사용자가 찾았다).
          안에 넣었더니 **아이 글과 한 덩어리**가 됐다 — 「저건 내가 안 썼는데 왜 내 글이랑
          같은 상자 안에 있지」. **결과 화면에서 방금 고친 것과 같은 종류를 여기에 만든 것**이다:
          담에 넣는 순간 **소유가 섞인다.**
          `장면카드_초안.md` 도 이쪽 편이다 — **「탐험가는 어떻게 할까?」는 상황문의 마지막 문장**이고
          **UI 가 자동으로 붙이는 것**이지 아이가 쓰는 칸의 일부가 아니다.
          **테두리 안에는 아이가 쓴 것과 아이가 하는 것(나침반·보내기)만 남는다.** */}
      {/* **나침반이 물음 줄로 올라왔다** (2026-09-09, 대사 1.4b 와 짝을 맞춘다).
          가이드가 **「여기 이 나침반, 네 말을 따라 움직여」**라고 가리키는데 **가리킬 대상이
          화면 반대편(상자 안 오른쪽 아래)에 있었다** — 둘 다 제자리인데 **지시어가 그 사이를 못 건넜다.**

          **셋째 길을 골랐다: 나침반을 가이드 쪽으로 올리되 쓰는 자리 바로 위에 둔다.**
          ① **가이드 대사 바로 아래 같은 열**이라 「여기 이」가 닿는다
          ② **글자 바로 위**라 쓰는 동안 시야에 있다 — 대사 옆까지 올리면 자판이 올라올 때 사라진다
          ③ **상자 밖이라 소유가 안 섞인다.** 「여기 이 나침반」이면 **그건 가이드의 물건**이고,
             테두리 안은 **아이가 쓴 것과 아이가 하는 것**만 두기로 한 그 규칙 그대로다

          **잃는 것 — 「차오른다 → 누른다」 짝.** 「보내기」 옆에 둬서 정체를 읽히게 했던 것인데,
          **이제 대사가 그 일을 말로 한다.** 자리로 설명하던 것을 문장이 대신하므로 짝을 놓아준다. */}
      {/* ⛔ **제목이 화면에서 안 보인다** (2026-09-22 사용자 지시 · `문구.md` 1.18).
          래서판다가 바로 위에서 **같은 질문**을 하는데 이 제목이 그것을 되풀이했다 —
          **묻는 것은 래서판다 하나**다.
          ⛔ **라벨 자체를 없애지 않는다.** 화면을 못 보는 아이에게는 **쓰는 칸에 이름이
          있어야** 하고, `htmlFor` 로 이어져 있어 읽어 주는 기계가 이 문장을 읽는다.
          ⭐ **`sr-only` 는 이 저장소가 이미 쓰는 방법**이다(본편의 단계 알림 줄).

          ## ⛔ 2026-09-24 에 이 줄을 제목 행 밖으로 꺼냈다 (사용자 지시)

          **행 안에 두면 행이 남는다.** 읽어 주는 기계에만 남긴 이름인데 화면에서는
          **빈 줄 하나**가 됐다 — 튜토리얼 세 화면에서 **라벨 24px + 뒤 간격 8px = 32px**
          (모바일 30px)이 입력칸 위에 떠 있었다(2026-09-24 실측).
          **본편은 `.chapter-console` 전용 `:has()` 규칙으로 그 행을 접고 있었고,
          튜토리얼(`.game-console`)에는 그 규칙이 없어 둘이 갈렸다.**

          ⭐ **화면별 CSS 로 가리지 않고 구조로 푼다** — 이름은 **행 밖**에 두고,
          **행은 보이는 것이 있을 때만** 그린다. `sr-only` 는 `position: absolute` 라
          **흐름 밖**이므로(실측) 여기서 부모의 간격을 만들지 않는다.
          ⛔ **`display: none` 으로 만들지 않았다** — 그러면 읽어 주는 기계에서도 사라진다. */}
      <label htmlFor="attempt" className="sr-only">
        {label}
      </label>
      {/* **보이는 것이 하나라도 있을 때만 제목 행을 그린다.** 지금 화면에 서는 것은
          나침반뿐이고, 보이는 제목이 다시 필요해지면 `제목보임` 이 그 자리를 연다. */}
      {(제목보임 || showCompass) && (
        <div className="attempt-label">
          {제목보임 && <span className="attempt-label-text">{label}</span>}
          {/* 길이는 **가린 뒤 문장 기준**이다 — 화면·로그·책이 같은 문자열을 센다. */}
          {showCompass && <CompassGlow length={value.length} introducing={introduction?.phase === "compass"} />}
        </div>
      )}
      <div
        className="writing-surface"
      >
        <textarea
        id="attempt"
        ref={입력창}
        value={value}
        // 쓰기 시작하면 소개를 끝낸다. 이후 나침반의 빛은 아이 입력에만 반응한다.
        onInput={introduction?.phase !== "complete" ? introduction?.finish : undefined}
        onCompositionStart={() => {
          조합중.current = true;
        }}
        onCompositionEnd={(e) => {
          조합중.current = false;
          // 조합이 끝난 지금 검사한다. `onChange` 가 조합 중에 그냥 흘려보냈기 때문이다.
          가리고전달(e.currentTarget.value, e.currentTarget.selectionStart);
        }}
        onChange={(e) => {
          if (조합중.current) {
            // 조합 중에는 **그대로 흘려보낸다.** 가리는 것은 조합이 끝난 뒤다.
            onChange(e.target.value);
            return;
          }
          가리고전달(e.target.value, e.target.selectionStart);
        }}
          // 보내는 중에는 잠근다. 값은 그대로 두어 **쓴 것이 눈앞에 남아 있게** 한다.
          readOnly={disabled}
          // **칸의 크기는 「얼마나 쓰는가」를 말하는 신호다.** 4줄은 짧게 쓰라는 뜻이었다 —
          // H2 합격선이 **회당 150자**다. 더 키우지 않는 것은 **아이패드에서 자판이 올라오면
          // 화면의 절반이 사라지기 때문**이고, 그때 「보내기」가 밖으로 밀리면 안 된다.
          rows={5}
        // **없으면 아예 속성을 안 단다.** 빈 문자열을 주면 브라우저가 빈 placeholder 를
        // 들고 있게 되고, 「비었다」와 「안 쓴다」가 코드에서 안 갈린다.
        placeholder={안내글}
        // 아이가 쓰는 칸이다. 맞춤법 빨간 줄로 「틀렸다」는 인상을 주지 않는다.
        spellCheck={false}
        autoComplete="off"
        // 테두리는 **비어 있을 때도 보여야 한다.** 배경색만으로 칸을 나타내면
        // 밝은 배경에서 칸이 사라져 아이가 어디에 쓰는지 모른다 — 첫 스크린샷에서 실제로 그랬다.
          // 테두리와 배경은 위 감싸개가 가진다. 여기는 **글자만** 둔다 —
          // 안에 또 테두리를 그리면 **상자 안의 상자**가 되어 덩어리가 다시 갈라진다.
          // `placeholder` 를 **흐리게** 둔다 — 아이가 쓴 글자와 같은 색이면
          // **자기가 쓴 줄 알고 지우려 든다.**
          className="writing-field"
        />

        {/* 「보내기」는 **상자 안에 남는다** — 쓰던 자리와 보내는 자리를 떼어놓지 않는다.
            **아이가 하는 것**이라 아이 테두리 안이 맞다. */}
        <div className="writing-actions">
          <button
            type="button"
            disabled={!보낼수있나}
            aria-busy={보내는중}
            onClick={onSend}
            className="pressable action-primary"
          >
            {보내는중 && <span className="leave-spinner" aria-hidden="true" />}
            {보내기라벨}
          </button>
        </div>
      </div>
      {안내 && (
        // 가린 이유를 말해주는 **유일한 자리**다. 전송을 막지 않으므로, 이 한 줄이 없으면
        // 아이는 자기 글자가 왜 바뀌었는지 알 방법이 없다.
        // 가이드 캐릭터 표정은 쓰지 않는다 — 제출 전 표정은 `default` 고정이다 (`Stage0.md` 3절).
        <p role="status" className="text-base text-accent">
          {안내}
        </p>
      )}
    </div>
  );
}
