import { describe, expect, it } from "vitest";

import { 대기대사하나, 삽화대기대사 } from "./artwork-copy";

/**
 * `docs/문구.md` **1.5**. **문장 자체를 여기서 다시 적지 않는다** — 그러면 문구가 바뀌는 날
 * 테스트가 제품을 붙잡는다. 여기서 막는 것은 **고르는 쪽이 목록 밖으로 나가는 것**이다.
 */
describe("삽화 대기 대사", () => {
  it("고른 것은 언제나 목록 안에 있다 — 빈 화면이 나오지 않는다", () => {
    // 인덱스가 한 칸 어긋나면 `undefined` 가 그대로 화면에 간다.
    // **6~8초 동안 아무 말도 없는 액자**가 되는데, 그건 대기 대사를 안 넣은 것과 같다.
    for (let i = 0; i < 200; i += 1) {
      expect(삽화대기대사).toContain(대기대사하나());
    }
  });

  it("여섯이 서로 다르다 — 같은 문장이 두 번 들어가 있으면 고르는 값이 준다", () => {
    expect(new Set(삽화대기대사).size).toBe(삽화대기대사.length);
  });
});
