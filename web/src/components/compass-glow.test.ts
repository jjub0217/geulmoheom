import { describe, expect, it } from "vitest";

import { 나침반밝기 } from "./compass-glow";

/**
 * **두 구간이 다 살아 있어야 한다.** 2026-09-09 실기기에서 **빈 상태와 6자가 눈으로 같았고**,
 * **30자 뒤로는 아무 변화가 없었다** — H2 합격선이 회당 150자인데 **우리가 원하는 구간에서
 * 신호가 0** 이었다. 검사 154개가 그때도 전부 초록이었다.
 */
describe("나침반 밝기", () => {
  it("빈 칸은 0 이다 — 꺼져 있는 것이 아니라 조용한 것이고, 그건 원 자체가 맡는다", () => {
    expect(나침반밝기(0)).toBe(0);
    expect(나침반밝기(-3)).toBe(0);
  });

  it("첫 몇 글자에서 눈에 띄게 움직인다 — 아이가 규칙을 배우는 자리다", () => {
    // 선형이면 3자에 0.065 라 **빈 것과 구분되지 않는다.** 그게 실기기에서 나온 결함이다.
    expect(나침반밝기(3)).toBeGreaterThan(0.25);
    expect(나침반밝기(6)).toBeGreaterThan(0.35);
  });

  it("30자에서 밝다 — PRD A0-2 MUST 「30자 넘으면 나침반 밝아짐」", () => {
    expect(나침반밝기(30)).toBeGreaterThanOrEqual(0.6);
  });

  it("30자를 넘어서도 계속 오른다 — 여기가 죽어 있으면 더 쓸 이유가 없다", () => {
    // **「30에서 가득」이 PRD 가 아니라 우리 구현이었다.** MUST 는 「30자 넘으면 밝아짐」뿐이다.
    expect(나침반밝기(60)).toBeGreaterThan(나침반밝기(30));
    expect(나침반밝기(100)).toBeGreaterThan(나침반밝기(60));
    expect(나침반밝기(150)).toBeGreaterThan(나침반밝기(100));
  });

  it("H2 합격선(150자)에서 가득 차고 넘어도 안 넘친다", () => {
    expect(나침반밝기(150)).toBe(1);
    expect(나침반밝기(400)).toBe(1);
  });

  it("길수록 밝다 — 어디서도 거꾸로 가지 않는다", () => {
    let 앞 = -1;
    for (let n = 0; n <= 200; n += 1) {
      const 지금 = 나침반밝기(n);
      expect(지금).toBeGreaterThanOrEqual(앞);
      앞 = 지금;
    }
  });
});
